import { describe, expect, it } from "vitest";
import { emptyCharacter } from "novel-ai-assistant/src/models/character";
import { emptyOrganization } from "novel-ai-assistant/src/models/organization";
import { emptyWorldItem } from "novel-ai-assistant/src/models/world";
import { emptyForeshadow } from "novel-ai-assistant/src/models/foreshadow";
import { MemoryFileStore } from "../src/platform/memoryFileStore";
import { findMaterial, readWorkMaterials } from "../src/platform/workMaterials";

const encode = (value: unknown) => new TextEncoder().encode(typeof value === "string" ? value : JSON.stringify(value));
const SET = "灯台守_確認用/設定";

describe("設定資料（E）を見る形にして読む（読むだけ）", () => {
  it("種類は本体の並び（人物・能力・組織・場所・世界観）に伏線を足し、ある種類だけ。欄は値のある所だけで、ローマ字は出さない", async () => {
    const store = new MemoryFileStore();
    const put = (path: string, value: unknown) => store.putExternally(`${SET}/${path}`, encode(value));
    put("characters/char_001.json", { ...emptyCharacter("char_001", "姉"), summary: "灯台に住む姉", romaji: "ane", affiliation: "灯台守の会", authorNotes: "妹には甘い" });
    put("characters/char_002.json", { ...emptyCharacter("char_002", "灯"), autoGenerated: false, exportNote: "書き出しにだけ載せる" });
    put("characters/char_003.json", { ...emptyCharacter("char_003", "船乗り"), isMob: true });
    put("organizations/org_001.json", emptyOrganization("org_001", "灯台守の会"));
    put("world/world_001_霧笛.json", { ...emptyWorldItem("world_001", "霧笛", "rule"), description: "霧の夜は三度鳴らす" });
    put("foreshadows/foreshadow_001_時計.json", { ...emptyForeshadow("foreshadow_001", "時計"), note: "父の形見", plantedChapter: 3 });
    const materials = await readWorkMaterials(store, SET);
    expect(materials.groups.map((g) => g.label)).toEqual(["登場人物", "組織", "世界観", "伏線"]);
    const sister = findMaterial(materials, "character", "char_001")!;
    expect(sister).toMatchObject({ name: "姉", summary: "灯台に住む姉", byAuthor: false, isMob: false });
    expect(sister.lines.map((l) => l.label)).toEqual(["紹介", "所属", "作者メモ"]);
    // 作者だけが書く欄には印（作者メモ・資料用の補足）
    expect(sister.lines.find((l) => l.label === "作者メモ")).toEqual({ label: "作者メモ", value: "妹には甘い", byAuthor: true });
    expect(sister.lines.find((l) => l.label === "紹介")!.byAuthor).toBeUndefined();
    expect(JSON.stringify(sister.lines)).not.toContain("ane");
    expect(findMaterial(materials, "character", "char_002")!.byAuthor).toBe(true);
    expect(findMaterial(materials, "character", "char_002")!.lines).toEqual([{ label: "資料用の補足", value: "書き出しにだけ載せる", byAuthor: true }]);
    expect(findMaterial(materials, "character", "char_003")!.isMob).toBe(true);
    // 組織の所属する人物は、人物の側の所属から引く（本体の membersOf）
    expect(findMaterial(materials, "organization", "org_001")!.lines).toContainEqual({ label: "所属する人物", value: "姉" });
    expect(findMaterial(materials, "world", "world_001")!.lines).toContainEqual({ label: "分類", value: "世界の法則" });
    const clock = findMaterial(materials, "foreshadow", "foreshadow_001")!;
    expect(clock.lines).toEqual([
      { label: "状態", value: "未回収" },
      { label: "示唆していること", value: "父の形見" },
      { label: "張った話", value: expect.stringContaining("3") },
    ]);
    expect(clock.byAuthor).toBe(true);
  });

  it("フォルダーが無ければ0件。壊れた1件・ファイル名と id が合わない1件は飛ばし、訳を残す。ファイルは書き換えない", async () => {
    const store = new MemoryFileStore();
    expect(await readWorkMaterials(store, SET)).toEqual({ groups: [], errors: [] });
    const put = (path: string, value: unknown) => store.putExternally(`${SET}/${path}`, encode(value));
    put("characters/char_001.json", emptyCharacter("char_001", "姉"));
    put("characters/char_009.json", "{ こわれている");
    put("characters/char_010.json", emptyCharacter("char_099", "別の人"));
    const materials = await readWorkMaterials(store, SET);
    expect(materials.groups[0]!.items.map((i) => i.name)).toEqual(["姉"]);
    expect(materials.errors.map((e) => e.file)).toEqual(["characters/char_009.json", "characters/char_010.json"]);
    expect(new TextDecoder().decode(await store.readFile(`${SET}/characters/char_009.json`))).toBe("{ こわれている");
  });

  it("知らない種類・id は見つからない（道の id から置き場の道を作らない）", async () => {
    const store = new MemoryFileStore();
    store.putExternally(`${SET}/characters/char_001.json`, encode(emptyCharacter("char_001", "姉")));
    const materials = await readWorkMaterials(store, SET);
    expect(findMaterial(materials, "character", "../char_001")).toBeUndefined();
    expect(findMaterial(materials, "nope", "char_001")).toBeUndefined();
  });
});

/** はじいた記述を行き先へ入れる（本体の「はじいた記述の行き先」と同じ。押した1件だけ書く） */
const MIXED_EPISODE = "姉から手紙が届いた。灯は背が高い、と姉は書いていた。港の守人は髭が白い、とも姉は書いていた。\n";

test("はじいた記述：［「灯」へ入れる］で既にいる人物の空欄へ、［「守人」を新しく起こして入れる］で新しい人物の資料を起こす。押すまで書かない", async ({ page }) => {
  await setUpAi(
    page,
    {
      ...SISTER_ANSWER,
      summary: null,
      role: null,
      misattributed: [
        { belongsTo: "灯", field: "appearance", value: "背が高い", evidence: "灯は背が高い" },
        { belongsTo: "守人", field: "appearance", value: "髭が白い", evidence: "港の守人は髭が白い" },
      ],
    },
    { ...MATERIALS, "灯台守_確認用/本文/第1話 手紙.txt": MIXED_EPISODE }
  );
  await openSisterEnrich(page);
  const before = await listFakeFiles(page, `${SET}/characters/`);
  await page.locator("#enrichRun").click();
  await page.locator('[data-answer="yes"]').click();
  const section = page.locator(".enrich-misattributed");
  await expect(section.locator(".enrich-place")).toHaveCount(2);
  await expect(section).toContainText("押すと、その人物の資料へ入れます");
  expect(await listFakeFiles(page, `${SET}/characters/`)).toEqual(before);
  await section.locator(".enrich-place", { hasText: "「灯」へ入れる" }).click();
  await expect(section.locator(".enrich-placed")).toHaveText("「灯」の空いていた項目へ入れました");
  const light = JSON.parse((await readFakeFile(page, `${SET}/characters/char_002.json`))!);
  expect(light.appearance).toBe("背が高い");
  expect(light.role).toBe("語り手");
  expect(light.autoGenerated).toBe(false);
  await section.locator(".enrich-place", { hasText: "「守人」を新しく起こして入れる" }).click();
  await expect(section.locator(".enrich-placed")).toHaveCount(2);
  const after = await listFakeFiles(page, `${SET}/characters/`);
  // 退避の控え（灯の元の資料）は数えない
  const added = after.filter((name) => !before.includes(name) && !name.includes(".novelai-recovery"));
  expect(added).toHaveLength(1);
  expect(added[0]).toMatch(/char_\d+_守人\.json$/);
  const guard = JSON.parse((await readFakeFile(page, added[0]!.startsWith(SET) ? added[0]! : `${SET}/characters/${added[0]}`))!);
  expect(guard).toMatchObject({ name: "守人", appearance: "髭が白い", autoGenerated: true });
  // 読み直した資料（姉）は書いていない
  await page.locator("#enrichDiscard").click();
  await expect(page).toHaveURL(/char_001$/);
});


import { expect, test, type Page } from "@playwright/test";
import { FAKE_WORKS, openWithWorks, readFakeFile } from "./support/fakeWorks";

/**
 * **左の線の欄（既定。ブラウザの入力欄 textarea）の打ち方を固める**（2026-11-17 作者の答え「左の欄も作り替える」。
 * 用語の色を付けるために欄を作り替えても、日本語入力の動きが今と変わらないことを、作り替えの前と後の両方で見る。
 * 引継ぎ書 87章）。
 *
 * 日本語入力は Chromium の CDP（`Input.imeSetComposition`・`Input.insertText`）で起こす。キーで打つより本物に近い
 * （compositionstart・変換中の字・確定が、端末の日本語入力と同じ順で来る）。作品は作り物（`_確認用`）だけ
 */

const EPISODE = "灯台守_確認用/本文/第1話 手紙.txt";
const ORIGINAL = "姉から手紙が届いた。\n// 付箋：ここは後で直す\n";
const COLORS_KEY = "novelai.leftLineTermColors";

/** 本体の `emptyCharacter` と同じ形の人物（e2e からは本体の部品を読めないので、形を写す） */
const character = (id: string, name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.1","aliases":[],"distinctFrom":[],"reading":null,"romaji":null,"icon":null,"iconSource":"none","summary":null,"gender":null,"affiliation":null,"role":null,"personality":null,"personalityFacets":[],"speechStyle":null,"speechStyleFacets":[],"appearance":null,"physical":null,"firstPerson":{"default":null,"variants":[]},"defaultSecondPerson":null,"addressTerms":[],"relations":[],"rejectedRelations":[],"abilities":[],"appearedChapters":[],"status":"登場済み","spoilerLevel":"public","authorNotes":"","exportNote":"","autoGenerated":true,"isMob":false,"evidence":null,"conflicts":[],"changes":[],"aiNotes":[],"customFields":{},"updatedAt":""}, id, name, ...extra });

const SISTER = character("char_001", "姉");
const WITH_TERMS = { ...FAKE_WORKS, "灯台守_確認用/設定/characters/char_001.json": SISTER };

async function openEpisode(page: Page, colors: boolean): Promise<void> {
  await page.addInitScript(
    ([key, on]) => {
      try {
        if (on) window.localStorage.setItem(key as string, "on");
      } catch {
        /* 覚えられなくても試せる */
      }
    },
    [COLORS_KEY, colors] as const
  );
  await openWithWorks(page, "#/works", WITH_TERMS);
  await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
  await page.locator(".ep-list .ep").first().click();
  await expect(page.locator("textarea#msEditor")).toBeVisible();
  await expect(page.locator("#msEditor")).toHaveValue(ORIGINAL);
}

/** 日本語入力：読みを変換中にして（下線の付いた字）、候補で確定する */
async function imeType(page: Page, reading: string, commit: string): Promise<void> {
  const cdp = await page.context().newCDPSession(page);
  for (let n = 1; n <= reading.length; n++) {
    const part = reading.slice(0, n);
    await cdp.send("Input.imeSetComposition", { text: part, selectionStart: part.length, selectionEnd: part.length });
  }
  await cdp.send("Input.imeSetComposition", { text: commit, selectionStart: commit.length, selectionEnd: commit.length });
  await cdp.send("Input.insertText", { text: commit });
  await cdp.detach();
}

/** 1つ目の行の終わり（「届いた。」の後ろ）にカーソル */
async function caretAfterFirstLine(page: Page): Promise<void> {
  const editor = page.locator("#msEditor");
  await editor.focus();
  await editor.evaluate((el: HTMLTextAreaElement) => {
    const at = el.value.indexOf("\n");
    el.setSelectionRange(at, at);
  });
}

for (const colors of [false, true]) {
  test.describe(`左の線の欄の打ち方（用語の色 ${colors ? "付ける（テスト中）" : "付けない（既定）"}）`, () => {
    test.skip(({ browserName }) => browserName !== "chromium", "日本語入力は Chromium の CDP で起こす");

    test("日本語入力で変換して確定すると、確定した字だけが入り、保存される", async ({ page }) => {
      await openEpisode(page, colors);
      await caretAfterFirstLine(page);
      await imeType(page, "とうだい", "灯台");
      const editor = page.locator("#msEditor");
      await expect(editor).toHaveValue("姉から手紙が届いた。灯台\n// 付箋：ここは後で直す\n");
      expect(await editor.evaluate((el: HTMLTextAreaElement) => el.selectionStart)).toBe("姉から手紙が届いた。灯台".length);
      await expect(page.locator("#saveState")).toHaveText("保存済み", { timeout: 6000 });
      expect(await readFakeFile(page, EPISODE)).toBe("姉から手紙が届いた。灯台\n// 付箋：ここは後で直す\n");
    });

    test("改行・⌫・選んだ字への打ち替えが、そのまま本文になる", async ({ page }) => {
      await openEpisode(page, colors);
      await caretAfterFirstLine(page);
      await page.keyboard.press("Enter");
      await page.keyboard.type("灯");
      await page.keyboard.press("Backspace");
      await page.keyboard.type("海");
      const editor = page.locator("#msEditor");
      await expect(editor).toHaveValue("姉から手紙が届いた。\n海\n// 付箋：ここは後で直す\n");
      // 「手紙」を選んで打ち替える
      await editor.evaluate((el: HTMLTextAreaElement) => el.setSelectionRange(3, 5));
      await imeType(page, "はがき", "葉書");
      await expect(editor).toHaveValue("姉から葉書が届いた。\n海\n// 付箋：ここは後で直す\n");
    });

    test("［取り消し］で打つ前に戻る", async ({ page }) => {
      await openEpisode(page, colors);
      await caretAfterFirstLine(page);
      await imeType(page, "とうだい", "灯台");
      await page.waitForTimeout(800);
      await page.locator('[data-tool="undo"]').click();
      await expect(page.locator("#msEditor")).toHaveValue(ORIGINAL);
    });
  });
}

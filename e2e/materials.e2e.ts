test("1件 →［本文から読み直す］→ 留意点 → 見積もり → 有料の確認 → 案。空欄を埋める案だけ選ばれている。［選んだ項目を反映］で資料に書く", async ({ page }) => {
  const ai = await setUpAi(page, SISTER_ANSWER);
  await openSisterEnrich(page);
  await expect(page.locator(".estimate")).toContainText("名前の出る場面");
  await page.locator("#enrichNotes").fill("灯の情報が混ざっています");
  await page.locator("#enrichRun").click();
  await page.locator('[data-answer="yes"]').click();
  await expect(page.locator(".enrich-row")).toHaveCount(2);
  expect(ai.calls()).toBe(1);
  // 頼みに本文の場面と留意点が入る（本体の頼みの文）
  expect(ai.bodies[0]).toContain("姉から手紙が届いた");
  expect(ai.bodies[0]).toContain("灯の情報が混ざっています");
  const role = page.locator('.enrich-row[data-key="role"]');
  const summary = page.locator('.enrich-row[data-key="summary"]');
  await expect(role.locator(".enrich-check")).toBeChecked();
  await expect(summary.locator(".enrich-check")).not.toBeChecked();
  await expect(summary).toContainText("現在の内容を置き換えます");
  await expect(summary).toContainText("現在：灯台に住む姉");
  // 押すまでは書かない
  expect(JSON.parse((await readFakeFile(page, `${SET}/characters/char_001.json`))!).role).toBeNull();
  // 案は手で直せる
  await role.locator(".enrich-after").fill("灯の姉");
  await page.locator("#enrichApply").click();
  await expect(page).toHaveURL(/char_001$/);
  await expect(page.locator(".materials-detail")).toContainText("灯の姉");
  const saved = JSON.parse((await readFakeFile(page, `${SET}/characters/char_001.json`))!);
  expect(saved.role).toBe("灯の姉");
  expect(saved.summary).toBe("灯台に住む姉");
  expect(saved.autoGenerated).toBe(true);
  expect(saved.customFields).toEqual({ birthday: "三月三日" });
});


import { describe, expect, test } from "vitest";
import { MemoryFileStore } from "../src/platform/memoryFileStore";
import { CHAPTER_SYNOPSES_FILE, loadSynopses, saveSynopses } from "../src/platform/synopsisStore";
import { upsertSynopsis, type ChapterSynopsis } from "../src/shared";

/**
 * 各話あらすじの台帳（`設定/chapter_synopses.json`。本体の `core/synopsisStore.ts` と同じ形と守り）。
 * 作者のデータを書く道なので、書く前に落ちる試しを先に置く（2026-11-18 母艦）：
 * 作者が書いたものは上書きしない・作者のメモを残す・外で変わっていたら書かない・壊れた台帳は直さず止める・元は退避する
 */
const SETTINGS = "灯台守_確認用/設定";
const FILE = `${SETTINGS}/${CHAPTER_SYNOPSES_FILE}`;
const utf8 = (text: string) => new TextEncoder().encode(text);
const read = async (store: MemoryFileStore) => new TextDecoder().decode(await store.readFile(FILE));
const entry = (over: Partial<ChapterSynopsis> = {}): ChapterSynopsis => ({
  chapter: 1,
  fileName: "第1話 手紙.txt",
  title: "手紙",
  synopsis: "姉から手紙が届く。",
  sourceHash: "h1",
  model: "m",
  promptVersion: "2.2",
  autoGenerated: true,
  authorNotes: "",
  emotion: null,
  updatedAt: "2026-11-18T00:00:00.000Z",
  ...over,
});

describe("各話あらすじの台帳", () => {
  test("無ければ空で読み、保存すると本体と同じ形（2字下げ・末に改行）で作る", async () => {
    const store = new MemoryFileStore();
    const loaded = await loadSynopses(store, SETTINGS);
    expect(loaded.set.episodes).toEqual([]);
    const saved = await saveSynopses(store, SETTINGS, upsertSynopsis(loaded.set, entry()).set, loaded);
    expect(saved.ok).toBe(true);
    const text = await read(store);
    expect(text.endsWith("}\n")).toBe(true);
    expect(JSON.parse(text)).toMatchObject({ schemaVersion: "0.1", episodes: [{ chapter: 1, synopsis: "姉から手紙が届く。" }] });
    expect(text).toContain('\n  "schemaVersion"');
  });

  test("作者が書いたあらすじ（autoGenerated: false）は差し替えない。作者のメモは残す", async () => {
    const store = new MemoryFileStore();
    store.putExternally(FILE, utf8(JSON.stringify({ schemaVersion: "0.1", episodes: [entry({ synopsis: "作者の文", autoGenerated: false, authorNotes: "メモ" })] })));
    const loaded = await loadSynopses(store, SETTINGS);
    const next = upsertSynopsis(loaded.set, entry({ synopsis: "AI の文" }));
    expect(next.skippedByAuthor).toBe(true);
    await saveSynopses(store, SETTINGS, next.set, loaded);
    const after = JSON.parse(await read(store));
    expect(after.episodes[0]).toMatchObject({ synopsis: "作者の文", autoGenerated: false, authorNotes: "メモ" });
  });

  test("読んだあとで外で変わっていたら書かない（同期で入れ替わったなど）", async () => {
    const store = new MemoryFileStore();
    store.putExternally(FILE, utf8(JSON.stringify({ schemaVersion: "0.1", episodes: [entry()] })));
    const loaded = await loadSynopses(store, SETTINGS);
    store.putExternally(FILE, utf8(JSON.stringify({ schemaVersion: "0.1", episodes: [entry({ synopsis: "外で直した" })] })));
    const saved = await saveSynopses(store, SETTINGS, upsertSynopsis(loaded.set, entry({ chapter: 2, fileName: "第2話.txt" })).set, loaded);
    expect(saved.ok).toBe(false);
    expect(JSON.parse(await read(store)).episodes[0].synopsis).toBe("外で直した");
  });

  test("無かったのに、書くまでのあいだに外でできていたら上書きしない", async () => {
    const store = new MemoryFileStore();
    const loaded = await loadSynopses(store, SETTINGS);
    store.putExternally(FILE, utf8(JSON.stringify({ schemaVersion: "0.1", episodes: [entry({ synopsis: "先にできた" })] })));
    const saved = await saveSynopses(store, SETTINGS, upsertSynopsis(loaded.set, entry()).set, loaded);
    expect(saved.ok).toBe(false);
    expect(JSON.parse(await read(store)).episodes[0].synopsis).toBe("先にできた");
  });

  test("壊れた台帳は直さずに止める（読めない、と返し、書かない）", async () => {
    const store = new MemoryFileStore();
    store.putExternally(FILE, utf8("{ 壊れ"));
    await expect(loadSynopses(store, SETTINGS)).rejects.toThrow(CHAPTER_SYNOPSES_FILE);
    expect(await read(store)).toBe("{ 壊れ");
  });

  test("書き換えるときは、元の台帳を退避する（回復先に前の中身が残る）", async () => {
    const store = new MemoryFileStore();
    const before = JSON.stringify({ schemaVersion: "0.1", episodes: [entry()] });
    store.putExternally(FILE, utf8(before));
    const loaded = await loadSynopses(store, SETTINGS);
    const saved = await saveSynopses(store, SETTINGS, upsertSynopsis(loaded.set, entry({ chapter: 2, fileName: "第2話.txt" })).set, loaded);
    expect(saved.ok).toBe(true);
    const backup = saved.ok ? saved.recoveryPath : undefined;
    expect(backup).toContain(".novelai-recovery");
    expect(new TextDecoder().decode(store.peek(backup!)!)).toBe(before);
  });
});

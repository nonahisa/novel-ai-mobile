import { describe, expect, test } from "vitest";
import { DEFAULT_MEMO_MARKERS, SYNOPSIS_TEMPERATURE, emptySynopsisSet, upsertSynopsis, type ChapterSynopsis } from "../src/shared";
import { planSynopses, runSynopses } from "../src/platform/synopsisRun";
import type { ModelCall } from "../src/platform/typoCheck";

/** 各話あらすじの1話ぶん（段2。2026-11-18）。本物の AI は呼ばない */
const EPISODE = { fileName: "第1話 手紙.txt", chapterStart: 1, title: "手紙", isInitialName: false, text: "姉から手紙が届いた。\n霧の朝だった。\n" };
const answer = (over: Record<string, unknown> = {}) =>
  JSON.stringify({
    synopsis: "灯台に住む姉から手紙が届く。霧の朝のことだった。",
    subtitles: [],
    confidence: "high",
    emotion: { intensity: 3, valence: 1, dominant: "楽", reason: "静かな朝" },
    ...over,
  });
const calling = (text: string, seen: Parameters<ModelCall>[0][] = []): ModelCall => async (request) => {
  seen.push(request);
  return text;
};
const entry = (over: Partial<ChapterSynopsis>): ChapterSynopsis => ({
  chapter: 1, fileName: EPISODE.fileName, title: "手紙", synopsis: "前の文", sourceHash: "x", model: "m", promptVersion: "x", autoGenerated: true, authorNotes: "", emotion: null, updatedAt: null, ...over,
});

describe("どの話を作るか", () => {
  test("無ければ作る。作者が書いたものは作らない。本文・モデル・版が同じなら作らない", () => {
    const fresh = planSynopses(EPISODE, emptySynopsisSet(), "m", DEFAULT_MEMO_MARKERS);
    expect(fresh.map((p) => p.plan)).toEqual(["make"]);
    expect(fresh[0]!.label).toBe("第1話 手紙");
    const byAuthor = upsertSynopsis(emptySynopsisSet(), entry({ autoGenerated: false })).set;
    expect(planSynopses(EPISODE, byAuthor, "m", DEFAULT_MEMO_MARKERS)[0]!.plan).toBe("author");
    const same = upsertSynopsis(emptySynopsisSet(), entry({ sourceHash: fresh[0]!.hash, promptVersion: fresh[0]!.version })).set;
    expect(planSynopses(EPISODE, same, "m", DEFAULT_MEMO_MARKERS)[0]!.plan).toBe("fresh");
    expect(planSynopses(EPISODE, same, "別のモデル", DEFAULT_MEMO_MARKERS)[0]!.plan).toBe("make");
  });
  test("ファイル名が初期のまま（サブタイトルが無い）話だけ、サブタイトル案も頼む", () => {
    const plain = planSynopses({ ...EPISODE, fileName: "001.txt", title: null, isInitialName: true }, emptySynopsisSet(), "m", DEFAULT_MEMO_MARKERS);
    expect(plain[0]!.needsSubtitle).toBe(true);
    expect(plain[0]!.version).toContain("reader:none");
  });
});

describe("作る", () => {
  test("本体の頼みの文・揺らしで頼み、台帳に AI が作ったもの（autoGenerated: true）として差し込む", async () => {
    const seen: Parameters<ModelCall>[0][] = [];
    const parts = planSynopses(EPISODE, emptySynopsisSet(), "m", DEFAULT_MEMO_MARKERS);
    const result = await runSynopses(parts, EPISODE, emptySynopsisSet(), "m", ["姉"], calling(answer(), seen), undefined, () => "2026-11-18T00:00:00.000Z");
    expect(result.failures).toEqual([]);
    expect(seen[0]!.temperature).toBe(SYNOPSIS_TEMPERATURE);
    expect(seen[0]!.user).toContain("姉から手紙が届いた。");
    expect(result.set.episodes[0]).toMatchObject({ chapter: 1, fileName: EPISODE.fileName, autoGenerated: true, model: "m", sourceHash: parts[0]!.hash, promptVersion: parts[0]!.version });
    expect(result.made[0]!.synopsis).toContain("姉から手紙");
  });
  test("作者が書いたものは頼まない（AI を呼ばない）", async () => {
    const byAuthor = upsertSynopsis(emptySynopsisSet(), entry({ autoGenerated: false, synopsis: "作者の文" })).set;
    const parts = planSynopses(EPISODE, byAuthor, "m", DEFAULT_MEMO_MARKERS);
    const seen: Parameters<ModelCall>[0][] = [];
    const result = await runSynopses(parts, EPISODE, byAuthor, "m", [], calling(answer(), seen));
    expect(seen).toHaveLength(0);
    expect(result.set.episodes[0]!.synopsis).toBe("作者の文");
  });
  test("読めない答え・空のあらすじ・失敗は、その話の失敗にする（台帳は変えない）", async () => {
    const parts = planSynopses(EPISODE, emptySynopsisSet(), "m", DEFAULT_MEMO_MARKERS);
    for (const call of [calling("読めない"), calling(answer({ synopsis: "" })), (async () => { throw new Error("待ち切れました"); }) as ModelCall]) {
      const result = await runSynopses(parts, EPISODE, emptySynopsisSet(), "m", [], call);
      expect(result.failures).toHaveLength(1);
      expect(result.set.episodes).toEqual([]);
    }
  });
});

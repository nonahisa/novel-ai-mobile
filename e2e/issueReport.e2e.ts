/** ブラウザの置き場（IndexedDB `Disc`）の `full` に、UTF-8 で書いた形のファイルを置く。フォルダーの記録も作る */
async function putFile(page: Page, full: string, text: string): Promise<void> {
  await page.evaluate(
    async ([path, body]) => {
      const db = await new Promise<IDBDatabase>((resolve, reject) => {
        const request = indexedDB.open("Disc", 1);
        request.onsuccess = () => resolve(request.result);
        request.onerror = () => reject(request.error);
      });
      const tx = db.transaction(["FileStorage"], "readwrite");
      const store = tx.objectStore("FileStorage");
      const now = Date.now();
      const parts = path.split("/").filter((p) => p !== "");
      for (let i = 1; i < parts.length; i += 1) {
        const folder = `/${parts.slice(0, i).join("/")}`;
        store.put({ path: folder, folder: folder.slice(0, folder.lastIndexOf("/")), type: "directory", size: 0, ctime: now, mtime: now });
      }
      // 失敗の記録は UTF-8 を指定して読み書きする。Capacitor のブラウザ版は、そのときの中身を字のまま持つ
      const content = body;
      store.put({ path, folder: path.slice(0, path.lastIndexOf("/")), type: "file", size: content.length, ctime: now, mtime: now, content });
      await new Promise<void>((resolve, reject) => {
        tx.oncomplete = () => resolve();
        tx.onerror = () => reject(tx.error);
      });
      db.close();
    },
    [full, text] as const,
  );
}

/** ブラウザの置き場で `prefix` から始まるファイルを、場所と中身で返す */
async function filesUnder(page: Page, prefix: string): Promise<{ path: string; text: string }[]> {
  return page.evaluate(async (head) => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => {
      const request = indexedDB.open("Disc", 1);
      request.onsuccess = () => resolve(request.result);
      request.onerror = () => reject(request.error);
    });
    const records = await new Promise<{ path: string; type: string; content?: string }[]>((resolve, reject) => {
      const all = db.transaction(["FileStorage"], "readonly").objectStore("FileStorage").getAll();
      all.onsuccess = () => resolve(all.result as { path: string; type: string; content?: string }[]);
      all.onerror = () => reject(all.error);
    });
    db.close();
    return records
      .filter((r) => r.type === "file" && r.path.startsWith(head))
      .map((r) => {
        // Capacitor のブラウザ版は、UTF-8 を指定して書いた中身をそのまま持つ（指定なしは base64）
        const content = r.content ?? "";
        try {
          const binary = atob(content);
          return { path: r.path, text: new TextDecoder().decode(Uint8Array.from(binary, (c) => c.charCodeAt(0))) };
        } catch {
          return { path: r.path, text: content };
        }
      });
  }, prefix);
}

/** 失敗の記録の1件（`formatFailureRecord` と同じ形。時刻は手元の時計） */
function failureRecord(at: Date, context: string, fields: [string, string][]): string {
  const p = (n: number) => String(n).padStart(2, "0");
  const stamp = `${at.getFullYear()}-${p(at.getMonth() + 1)}-${p(at.getDate())} ${p(at.getHours())}:${p(at.getMinutes())}:${p(at.getSeconds())}`;
  return `[${stamp}] --- ${context} ---\n${fields.map(([k, v]) => `  ${k}: ${v}\n`).join("")}`;
}

async function openReport(page: Page): Promise<void> {
  await openWithWorks(page, "#/other", WITH_PEOPLE);
  const anHourAgo = new Date(Date.now() - 60 * 60 * 1000);
  await putFile(
    page,
    "/DATA/failure-log/actions.log",
    // 作品の題（config の workTitle）も、フォルダー名も、人物の別名も出す
    failureRecord(anHourAgo, "保存", [["種別", "path_conflict"], ["詳細", "灯台守_確認用/本文/第1話 手紙.txt（灯台守の手紙_確認用）で汐ちゃんと汐里の場面が書けませんでした"]]) +
      failureRecord(anHourAgo, "同期（送る）", [["種別", "offline"]]),
  );
  await page.goto("/#/other");
  const help = page.locator(".menu-section", { has: page.locator("h2", { hasText: "ヘルプ" }) });
  await help.locator(".menu-item", { hasText: "障害報告用の記録" }).click();
  await expect(page.locator("#reportMake")).toBeVisible();
}

test.describe("障害報告用の記録", () => {
  test("記録を作ると、失敗を数えて人物名・作品名を伏せ、約束の形の要約を見せる", async ({ page }) => {
    await openReport(page);
    await page.locator("#reportMake").click();
    await expect(page.locator("#reportId")).toHaveText(/^報告ID：NAI-\d{8}-[a-z0-9]{4}（失敗 2件）$/);
    const summary = (await page.locator("#reportSummary").textContent()) ?? "";
    expect(summary).toContain("製品: モバイル版");
    expect(summary).toContain("記録の形 1");
    expect(summary).toContain("失敗: 2種類・計2回");
    expect(summary).not.toContain("汐里");
    expect(summary).not.toContain("灯台守");
    await expect(page.locator(".report-masked")).toContainText("人物名・作品名");
    // ここではまだ置かない
    expect(await filesUnder(page, "/DOCUMENTS/")).toEqual([]);
    // 詳細（後半）にも、作品の題・フォルダー名・人物の名前と別名を残さない
    await page.locator("#reportDiscord").click();
    await expect(page.locator("#reportWhere")).toBeVisible();
    const [placed] = await filesUnder(page, "/DOCUMENTS/");
    for (const name of ["灯台守の手紙", "灯台守_確認用", "汐里", "汐ちゃん"]) expect(placed!.text).not.toContain(name);
  });

  test("アプリが失敗を記録の場所へ書き、記録の画面がそれを数える（画面の例外）", async ({ page }) => {
    await openWithWorks(page, "#/other", WITH_PEOPLE);
    // 画面の例外は `watchUncaughtFailures` が失敗の記録へ書く（本物の書く道：noteFailure → Filesystem）
    await page.evaluate(() => {
      setTimeout(() => {
        throw new Error("試しの例外");
      });
    });
    await expect
      .poll(async () => (await filesUnder(page, "/DATA/failure-log/")).map((f) => f.text).join(""))
      .toContain("--- 画面の例外 ---");
    const help = page.locator(".menu-section", { has: page.locator("h2", { hasText: "ヘルプ" }) });
    await help.locator(".menu-item", { hasText: "障害報告用の記録" }).click();
    await page.locator("#reportMake").click();
    await expect(page.locator("#reportId")).toHaveText(/（失敗 1件）$/);
    await expect(page.locator("#reportSummary")).toContainText("画面の例外");
  });

  test("［Discord で報告する］で Documents/小説執筆/<報告ID>.md に置き、手順と #不具合報告 のリンクを出す。外へは送らない", async ({ page }) => {
    const asked: string[] = [];
    await page.route(/discord\.(com|gg)/, (route) => {
      asked.push(route.request().url());
      return route.fulfill({ contentType: "text/html", body: "<title>Discord</title>" });
    });
    await openReport(page);
    await page.locator("#reportMake").click();
    const id = /NAI-\d{8}-[a-z0-9]{4}/.exec((await page.locator("#reportId").textContent()) ?? "")![0];
    await page.locator("#reportDiscord").click();
    await expect(page.locator("#reportWhere")).toHaveText(`Documents › 小説執筆 に ${id}.md を置きました`);
    await expect(page.locator(".report-steps li")).toHaveCount(5);
    await expect(page.locator("#reportShareWarn")).toHaveCount(0);
    await expect(page.locator("#reportChannel")).toHaveAttribute("href", CHANNEL);

    const placed = await filesUnder(page, "/DOCUMENTS/");
    expect(placed.map((f) => f.path)).toEqual([`/DOCUMENTS/小説執筆/${id}.md`]);
    const text = placed[0]!.text;
    expect(text.split("\n")[0]).toBe(`# 障害報告用の記録 ${id}`);
    expect(text).toContain("## 環境");
    expect(text).not.toContain("汐里");
    expect(text).not.toContain("灯台守");
    expect(asked).toEqual([]);
  });

  test("伏せないを選べば、人物名は記録に残る", async ({ page }) => {
    await openReport(page);
    await page.locator("#reportMask").uncheck();
    await page.locator("#reportMake").click();
    await expect(page.locator("#reportId")).toBeVisible();
    await page.locator("#reportDiscord").click();
    await expect(page.locator("#reportWhere")).toBeVisible();
    const [placed] = await filesUnder(page, "/DOCUMENTS/");
    expect(placed!.text).toContain("汐里");
  });
});

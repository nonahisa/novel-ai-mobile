import {
  FORESHADOW_STATUS_LABELS,
  KIND_LABELS,
  SETTINGS_KINDS,
  describeAbility,
  describeCharacter,
  describeLocation,
  describeOrganization,
  describeWorldItem,
  formatChapters,
  membersOf,
  parseAbility,
  parseCharacter,
  parseForeshadow,
  parseLocation,
  parseOrganization,
  parseWorldItem,
  type Foreshadow,
  type SettingsKind,
} from "../shared";
import type { FileStore } from "./fileStore";
import { readKind, type WorkTerms } from "./workTerms";

/**
 * **作品の設定資料を、見る形にして読む**（設計書 4章の画面 E。2026-11-21。読むだけで `設定/` へは書かない）。
 *
 * - 読み方は用語の色と同じ `readKind`（本体の検証を通す・壊れた1件は飛ばして訳を残す・`_` で始まるファイルは読まない）
 * - 種類の並びと名前は本体の `SETTINGS_KINDS`・`KIND_LABELS`（登場人物・能力・組織・場所・世界観）。伏線を末に足す
 * - 1件の欄は本体の `describe*`（`core/settingsSummary.ts`）が出す「名前: 値」の行をそのまま使う。値の入った欄だけが並び、
 *   ローマ字・id・時刻のような内部の欄は出ない。作中の変化（関与度つき。AI へ渡す形）は出さない（`omitChanges`）
 * - 作者が書いた・確かめた資料（`autoGenerated: false`）には「作者」、モブには「モブ」の印。作者だけが書く欄（作者メモ・
 *   資料用の補足・伏線の回収の予定）にも「作者」の印
 * - 作者が足した項目（`custom_fields.json`）・能力の体系は、まだ読まない
 */

export type MaterialKind = SettingsKind | "foreshadow";

export interface MaterialLine {
  label: string;
  value: string;
  /** 作者だけが書く欄（作者メモ・資料用の補足・伏線の回収の予定）。画面で「作者」の印を付ける（設計書 4章の E） */
  byAuthor?: true;
}

/** 作者だけが書く欄の名前（本体の settingsSummary・設定資料パネルと同じ名前） */
const AUTHOR_LINES = new Set(["作者メモ", "資料用の補足", "回収の予定"]);

/** 欄に作者の印を付け、資料用の補足（`exportNote`。本体の describe* は出さない）を作者メモの後ろに足す */
function withAuthorMarks(lines: MaterialLine[], exportNote = ""): MaterialLine[] {
  const marked = [...lines];
  if (exportNote.trim()) marked.push({ label: "資料用の補足", value: exportNote.trim() });
  return marked.map((line) => (AUTHOR_LINES.has(line.label) ? { ...line, byAuthor: true } : line));
}

export interface MaterialItem {
  kind: MaterialKind;
  id: string;
  name: string;
  /** 一覧で名前の下に出す短い紹介（無ければ空） */
  summary: string;
  byAuthor: boolean;
  isMob: boolean;
  /** 1件を開いたときの欄（見出しの名前の行は除く） */
  lines: MaterialLine[];
}

export interface MaterialGroup {
  kind: MaterialKind;
  label: string;
  items: MaterialItem[];
}

export interface WorkMaterials {
  /** 1件でもある種類だけ。本体の並び＋伏線 */
  groups: MaterialGroup[];
  errors: WorkTerms["errors"];
}

export const FORESHADOW_LABEL = "伏線";

/** 本体の describe* が出す「名前: 値」の行を欄に分ける。1行目（名前・見出し）は見出しに使うので除く */
export function linesOfDescription(text: string): MaterialLine[] {
  return text
    .split("\n")
    .slice(1)
    .flatMap((line) => {
      const at = line.indexOf(": ");
      return at > 0 ? [{ label: line.slice(0, at), value: line.slice(at + 2) }] : [];
    });
}

/** 伏線の欄（本体の settingsSummary には伏線が無いので、同じ「値の入った欄だけ」の決まりで並べる） */
export function foreshadowLines(item: Foreshadow): MaterialLine[] {
  const lines: MaterialLine[] = [];
  const push = (label: string, value: string | null | undefined) => {
    if (value && value.trim()) lines.push({ label, value: value.trim() });
  };
  const chapter = (value: number | null) => (value === null ? null : formatChapters([value]));
  push("状態", FORESHADOW_STATUS_LABELS[item.status]);
  push("示唆していること", item.note);
  push("張った話", chapter(item.plantedChapter));
  push("張った所", item.plantedQuote);
  push("回収した話", chapter(item.resolvedChapter));
  push("回収した所", item.resolvedQuote);
  push("回収の予定", chapter(item.plannedResolveChapter));
  push("作者メモ", item.authorNotes);
  return lines;
}

export async function readWorkMaterials(store: FileStore, settingsDir: string): Promise<WorkMaterials> {
  const errors: WorkTerms["errors"] = [];
  const characters = await readKind(store, settingsDir, "characters", parseCharacter, errors);
  const abilities = await readKind(store, settingsDir, "abilities", parseAbility, errors);
  const organizations = await readKind(store, settingsDir, "organizations", parseOrganization, errors);
  const locations = await readKind(store, settingsDir, "locations", parseLocation, errors);
  const world = await readKind(store, settingsDir, "world", parseWorldItem, errors);
  const foreshadows = await readKind(store, settingsDir, "foreshadows", parseForeshadow, errors);

  const item = (
    kind: MaterialKind,
    record: { id: string; autoGenerated: boolean; summary?: string | null; exportNote?: string },
    name: string,
    lines: MaterialLine[],
    isMob = false
  ): MaterialItem => ({
    kind,
    id: record.id,
    name,
    summary: record.summary?.trim() ?? "",
    byAuthor: !record.autoGenerated,
    isMob,
    lines: withAuthorMarks(lines, record.exportNote),
  });

  const byKind: Record<SettingsKind, MaterialItem[]> = {
    character: characters.map((c) => item("character", c, c.name, linesOfDescription(describeCharacter(c, [], { omitChanges: true, characters })), c.isMob)),
    ability: abilities.map((a) => item("ability", a, a.name, linesOfDescription(describeAbility(a)))),
    organization: organizations.map((o) => item("organization", o, o.name, linesOfDescription(describeOrganization(o, membersOf(o, characters))))),
    location: locations.map((l) => item("location", l, l.name, linesOfDescription(describeLocation(l)))),
    world: world.map((w) => item("world", { ...w, summary: w.description }, w.name, linesOfDescription(describeWorldItem(w)))),
  };
  const groups: MaterialGroup[] = SETTINGS_KINDS.map((kind) => ({ kind, label: KIND_LABELS[kind], items: byKind[kind] }));
  groups.push({
    kind: "foreshadow",
    label: FORESHADOW_LABEL,
    items: foreshadows.map((f) => item("foreshadow", { ...f, summary: f.note }, f.label, foreshadowLines(f))),
  });
  return { groups: groups.filter((group) => group.items.length > 0), errors };
}

/** 道（`#/materials/<作品>/<種類>/<id>`）の種類と id から、読んだ資料の1件を探す（id から置き場の道は作らない） */
export function findMaterial(materials: WorkMaterials, kind: string, id: string): MaterialItem | undefined {
  return materials.groups.find((group) => group.kind === kind)?.items.find((entry) => entry.id === id);
}

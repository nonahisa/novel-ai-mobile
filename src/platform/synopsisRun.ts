import {
  SYNOPSIS_SCHEMA,
  SYNOPSIS_SYSTEM_PROMPT,
  SYNOPSIS_TEMPERATURE,
  buildSynopsisPrompt,
  findSynopsis,
  parseSynopsisResult,
  splitEpisodeBodyParts,
  synopsisPromptVersion,
  upsertSynopsis,
  validateSynopsisResult,
  type ChapterSynopsisSet,
  type MemoMarkers,
  type SubtitleSuggestion,
} from "../shared";
import type { ModelCall } from "./typoCheck";

/**
 * **各話あらすじ**（段2。2026-11-18。本体の `features/generateSynopses.ts` の1話ぶんを、モバイル版の手で並べ直したもの）。
 *
 * 本体と同じところ：
 * - 本文の分け方・メモを消す・ハッシュは本体の `splitEpisodeBodyParts`（合本の中の話も1話ずつ）。ハッシュが同じなら、
 *   本体で作ったものも作り直さない（逆も同じ）
 * - 作り直すのは、無い・本文が変わった・モデルか頼みの版が変わったときだけ。**作者が書いたもの（`autoGenerated: false`）は触らない**
 * - 頼みの文・スキーマ・揺らし・答えの確かめ（150字・サブタイトル案の検算・感情の測り）・差し込み（`upsertSynopsis`）は本体の部品
 * - 前の話のあらすじは直前の3話ぶん、人物の名前はモブを除いて100まで（表記をそろえるため）
 *
 * 本体と違うところ：
 * - サブタイトル案は見せるだけで、ファイル名は変えない（本体は作者が選ぶとファイル名を変える。モバイル版ではまだ作らない）
 * - 読者像（設計書6.91）は読まない（`readerTypeMark` は未診断の "none"）。読者像を診断した作品では、サブタイトル案の回だけ
 *   頼みの版が本体と食い違い、本体で次に走らせたときに作り直される
 */

const PREVIOUS_SYNOPSES_LIMIT = 3;
const CHARACTER_NAME_LIMIT = 100;

/** 1話ぶんの元（話の一覧の1件から） */
export interface SynopsisEpisode {
  fileName: string;
  chapterStart: number | null;
  /** ファイル名のサブタイトル、無ければ本文の頭のメタの題 */
  title: string | null;
  /** ファイル名が初期のまま（サブタイトルが無い）か */
  isInitialName: boolean;
  /** 本文（LF） */
  text: string;
}

export interface SynopsisPart {
  chapter: number | null;
  title: string | null;
  body: string;
  hash: string;
  insideCollected: boolean;
  /** 作り直すか。作らないなら訳 */
  plan: "make" | "author" | "fresh";
  label: string;
  needsSubtitle: boolean;
  version: string;
}

export function synopsisLabel(part: Pick<SynopsisPart, "chapter" | "title">, fileName: string): string {
  if (part.chapter === null) return fileName.replace(/\.txt$/i, "");
  return part.title ? `第${part.chapter}話 ${part.title}` : `第${part.chapter}話`;
}

/** 走らせる前に、どの話を作るかを決める（見積もりの回数にも使う） */
export function planSynopses(episode: SynopsisEpisode, set: ChapterSynopsisSet, model: string, memoMarkers: MemoMarkers): SynopsisPart[] {
  return splitEpisodeBodyParts(episode.text, { chapter: episode.chapterStart, title: episode.title }, memoMarkers).map((part) => {
    const needsSubtitle = !part.insideCollected && episode.isInitialName && !part.title;
    const version = synopsisPromptVersion({ needsSubtitle, readerTypeMark: "none" });
    const existing = findSynopsis(set, episode.fileName, part.chapter);
    const plan: SynopsisPart["plan"] = !existing
      ? "make"
      : !existing.autoGenerated
        ? "author"
        : existing.sourceHash !== part.hash || existing.model !== model || existing.promptVersion !== version
          ? "make"
          : "fresh";
    return { ...part, plan, label: synopsisLabel(part, episode.fileName), needsSubtitle, version };
  });
}

function previousSynopsesFor(set: ChapterSynopsisSet, chapter: number | null): string[] {
  if (chapter === null) return [];
  return set.episodes
    .filter((item) => item.chapter !== null && item.chapter < chapter)
    .slice(-PREVIOUS_SYNOPSES_LIMIT)
    .map((item) => `第${item.chapter}話: ${item.synopsis}`);
}

export interface SynopsisRunResult {
  set: ChapterSynopsisSet;
  /** 作った話（ラベルとあらすじ） */
  made: { label: string; synopsis: string; subtitles: SubtitleSuggestion[] }[];
  failures: { label: string; reason: string }[];
  calls: number;
}

export async function runSynopses(
  parts: readonly SynopsisPart[],
  episode: Pick<SynopsisEpisode, "fileName">,
  start: ChapterSynopsisSet,
  model: string,
  characterNames: readonly string[],
  call: ModelCall,
  signal?: AbortSignal,
  now: () => string = () => new Date().toISOString()
): Promise<SynopsisRunResult> {
  let set = start;
  const result: SynopsisRunResult = { set, made: [], failures: [], calls: 0 };
  const names = [...new Set(characterNames)].slice(0, CHARACTER_NAME_LIMIT);
  for (const part of parts) {
    if (part.plan !== "make") continue;
    if (signal?.aborted) break;
    let text: string;
    try {
      result.calls++;
      text = await call({
        system: SYNOPSIS_SYSTEM_PROMPT,
        user: buildSynopsisPrompt({
          chapterLabel: part.label,
          chapterText: part.body,
          previousSynopses: previousSynopsesFor(set, part.chapter),
          characterNames: names,
          needsSubtitle: part.needsSubtitle,
        }),
        schema: SYNOPSIS_SCHEMA,
        temperature: SYNOPSIS_TEMPERATURE,
        ...(signal ? { signal } : {}),
      });
    } catch (error) {
      if (signal?.aborted) break;
      result.failures.push({ label: part.label, reason: error instanceof Error ? error.message : String(error) });
      continue;
    }
    const parsed = parseSynopsisResult(text);
    if (!parsed) {
      result.failures.push({ label: part.label, reason: "AI の答えが読めませんでした" });
      continue;
    }
    const validated = validateSynopsisResult(parsed);
    if (!validated.synopsis) {
      result.failures.push({ label: part.label, reason: "あらすじが空でした" });
      continue;
    }
    set = upsertSynopsis(set, {
      chapter: part.chapter,
      fileName: episode.fileName,
      title: part.title,
      synopsis: validated.synopsis,
      sourceHash: part.hash,
      model,
      // 作ったときと同じ版を控える（判定と食い違うと、毎回作り直すか、二度と作り直さないかになる）
      promptVersion: part.version,
      autoGenerated: true,
      authorNotes: "",
      emotion: validated.emotion,
      updatedAt: now(),
    }).set;
    result.made.push({ label: part.label, synopsis: validated.synopsis, subtitles: part.needsSubtitle ? validated.subtitles : [] });
  }
  result.set = set;
  return result;
}

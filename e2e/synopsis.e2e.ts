import { expect, test, type Page } from "@playwright/test";
import { FAKE_WORKS, openWithWorks, readFakeFile } from "./support/fakeWorks";

/**
 * **各話あらすじ**（段2。2026-11-18）：話の長押し → あらすじ → 見積もり → 有料の確認 → 台帳（`設定/chapter_synopses.json`）へ書く。
 * 作者が書いたあらすじは触らない。本文が変わっていなければ作り直さない。Anthropic は偽物。作品は作り物（`_確認用`）だけ
 */
const CORS = { "access-control-allow-origin": "*", "access-control-allow-headers": "*" };
const LEDGER = "灯台守_確認用/設定/chapter_synopses.json";
const byAuthor = {
  chapter: 2, fileName: "第2話.txt", title: null, synopsis: "作者が書いた第2話のあらすじ", sourceHash: "x", model: null, promptVersion: null,
  autoGenerated: false, authorNotes: "作者のメモ", emotion: null, updatedAt: null,
};

async function setUp(page: Page): Promise<{ calls: () => number }> {
  let calls = 0;
  await page.route("https://api.anthropic.com/v1/models**", (route) =>
    route.fulfill({ headers: CORS, contentType: "application/json", body: JSON.stringify({ data: [{ id: "claude-a" }] }) })
  );
  await page.route("https://api.anthropic.com/v1/messages", (route) => {
    if (route.request().method() === "OPTIONS") return route.fulfill({ headers: CORS });
    calls++;
    const answer = { synopsis: "灯台に住む姉から手紙が届く。", subtitles: [], confidence: "high", emotion: { intensity: 3, valence: 1, dominant: "楽", reason: "静かな朝" } };
    return route.fulfill({ headers: CORS, contentType: "application/json", body: JSON.stringify({ content: [{ type: "text", text: JSON.stringify(answer) }], stop_reason: "end_turn" }) });
  });
  await openWithWorks(page, "#/ai", { ...FAKE_WORKS, [LEDGER]: JSON.stringify({ schemaVersion: "0.1", episodes: [byAuthor] }) });
  await page.locator('[data-ai-set="claude"]').click();
  await page.locator("#dialogInput").fill("sk-ant-tukurimono-synopsis");
  await page.locator('[data-answer="yes"]').click();
  await page.locator("[data-ai-default]").click();
  await page.locator('[data-choice="claude"]').click();
  await page.locator('[data-choice="claude-a"]').click();
  await expect(page.locator("#aiDefault")).toContainText("claude-a");
  return { calls: () => calls };
}

async function longPressFirstEpisode(page: Page): Promise<void> {
  await page.evaluate(() => (location.hash = "#/works"));
  await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
  const box = (await page.locator(".ep-list .ep").first().boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.waitForTimeout(700);
  await page.mouse.up();
  await page.locator(".dialog-choices button", { hasText: "あらすじ" }).click();
  await expect(page).toHaveURL(/#\/synopsis\//);
}

test("話の長押しからあらすじを作り、台帳に書く。作者が書いた話はそのまま。本文が同じなら作り直さない", async ({ page }) => {
  const ai = await setUp(page);
  await longPressFirstEpisode(page);
  await expect(page.locator(".estimate")).toContainText("第1話 手紙");
  await expect(page.locator(".estimate")).toContainText("1 回");
  await page.locator("#typoRun").click();
  await page.locator('[data-answer="yes"]').click();
  await expect(page.locator("#typoProgress")).toHaveText("1話のあらすじを書きました");
  await expect(page.locator(".synopsis-row")).toContainText("灯台に住む姉から手紙が届く。");
  expect(ai.calls()).toBe(1);

  const ledger = JSON.parse((await readFakeFile(page, LEDGER))!);
  expect(ledger.schemaVersion).toBe("0.1");
  const first = ledger.episodes.find((e: { chapter: number }) => e.chapter === 1);
  expect(first).toMatchObject({ fileName: "第1話 手紙.txt", synopsis: "灯台に住む姉から手紙が届く。", autoGenerated: true, model: "claude-a" });
  expect(ledger.episodes.find((e: { chapter: number }) => e.chapter === 2)).toEqual(byAuthor);

  // もう一度開くと、作り直さない（AI を呼ばない）
  await longPressFirstEpisode(page);
  await expect(page.locator("#typoProblem")).toHaveText("本文が変わっていないので、作り直しません");
  await expect(page.locator(".synopsis-row")).toContainText("灯台に住む姉から手紙が届く。");
  expect(ai.calls()).toBe(1);
});

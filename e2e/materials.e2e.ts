import { expect, test, type Page } from "@playwright/test";
import { FAKE_WORKS, listFakeFiles, openWithWorks, readFakeFile } from "./support/fakeWorks";

/**
 * **設定資料（E）を見る**（設計書 4章の画面 E。2026-11-21）：［ほか］→ 設定資料 → 作品を選ぶ → 種類ごとの一覧 → 1件。
 * 読むだけで `設定/` へは書かない。作者が書いた資料には「作者」の印。読めなかったファイルは訳と並べる。作品は作り物（`_確認用`）だけ
 */

/** 本体の `emptyCharacter` などと同じ形（e2e からは本体の部品を読めないので、形を写す） */
const character = (id: string, name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.1","aliases":[],"distinctFrom":[],"reading":null,"romaji":null,"icon":null,"iconSource":"none","summary":null,"gender":null,"affiliation":null,"role":null,"personality":null,"personalityFacets":[],"speechStyle":null,"speechStyleFacets":[],"appearance":null,"physical":null,"firstPerson":{"default":null,"variants":[]},"defaultSecondPerson":null,"addressTerms":[],"relations":[],"rejectedRelations":[],"abilities":[],"appearedChapters":[],"status":"登場済み","spoilerLevel":"public","authorNotes":"","exportNote":"","autoGenerated":true,"isMob":false,"evidence":null,"conflicts":[],"changes":[],"aiNotes":[],"customFields":{},"updatedAt":""}, id, name, ...extra });
const location = (id: string, name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.1","aliases":[],"reading":null,"summary":null,"region":null,"description":null,"appearedChapters":[],"status":"登場済み","spoilerLevel":"public","evidence":null,"authorNotes":"","exportNote":"","autoGenerated":true,"conflicts":[],"aiNotes":[],"updatedAt":""}, id, name, ...extra });
const world = (id: string, name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.1","aliases":[],"reading":null,"category":"rule","description":null,"appearedChapters":[],"spoilerLevel":"public","evidence":null,"authorNotes":"","exportNote":"","autoGenerated":true,"conflicts":[],"aiNotes":[],"updatedAt":""}, id, name, ...extra });
const foreshadow = (id: string, label: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.2","note":"","plantedChapter":null,"plantedQuote":"","status":"open","resolvedChapter":null,"resolvedQuote":"","plannedResolveChapter":null,"source":"author","autoGenerated":false,"authorNotes":"","createdAt":"","updatedAt":""}, id, label, ...extra });

const SET = "灯台守_確認用/設定";
const MATERIALS: Record<string, string> = {
  ...FAKE_WORKS,
  [`${SET}/characters/char_001.json`]: character("char_001", "姉", { summary: "灯台に住む姉", personality: "静か", romaji: "ane", authorNotes: "妹には甘い", appearedChapters: [1, 2] }),
  [`${SET}/characters/char_002.json`]: character("char_002", "灯", { autoGenerated: false, role: "語り手" }),
  [`${SET}/characters/char_003.json`]: character("char_003", "船乗り", { isMob: true }),
  // 壊れた1件は飛ばして、残りを読む（直さない）
  [`${SET}/characters/char_009.json`]: "{ こわれている",
  [`${SET}/locations/loc_001.json`]: location("loc_001", "灯台", { description: "岬の先の白い灯台" }),
  [`${SET}/world/world_001_霧笛の決まり.json`]: world("world_001", "霧笛の決まり", { description: "霧の夜は三度鳴らす" }),
  [`${SET}/foreshadows/foreshadow_001_銀の懐中時計.json`]: foreshadow("foreshadow_001", "銀の懐中時計", { note: "父の形見", plantedChapter: 1 }),
};

const pressBack = (page: Page) => page.evaluate(() => document.dispatchEvent(new Event("backbutton")));

async function openMaterials(page: Page): Promise<void> {
  await openWithWorks(page, "#/other", MATERIALS);
  await page.locator('[data-screen="materials"]').click();
  await expect(page).toHaveURL(/#\/materials$/);
  // 作品が何作かあれば、先に選ぶ
  await page.locator(".materials-work", { hasText: "灯台守の手紙_確認用" }).click();
  await expect(page).toHaveURL(/#\/materials\//);
}

test("［ほか］→ 設定資料：作品を選ぶと、種類ごとに資料が並ぶ。作者が書いた資料には印。読めなかったファイルは訳と並べる", async ({ page }) => {
  await openMaterials(page);
  const kinds = page.locator(".materials-kind h2");
  await expect(kinds).toHaveText(["登場人物", "場所", "世界観", "伏線"]);
  const people = page.locator(".materials-kind", { has: page.locator("h2", { hasText: "登場人物" }) });
  await expect(people.locator(".materials-row")).toHaveCount(3);
  await expect(people.locator(".materials-row", { hasText: "姉" })).toContainText("灯台に住む姉");
  await expect(people.locator(".materials-row", { hasText: "灯" }).filter({ hasNotText: "姉" }).locator(".flag")).toHaveText("作者");
  await expect(people.locator(".materials-row", { hasText: "船乗り" }).locator(".flag")).toHaveText("モブ");
  await expect(page.locator(".materials-kind", { has: page.locator("h2", { hasText: "伏線" }) })).toContainText("銀の懐中時計");
  const errors = page.locator(".materials-errors");
  await expect(errors).toContainText("読めなかった資料");
  await expect(errors).toContainText("characters/char_009.json");
});

test("1件を押すと中身が出る（値のある欄だけ。ローマ字は出さない）。［戻る］キーで一覧へ。資料のファイルは書き換えない", async ({ page }) => {
  const before = await (async () => {
    await openWithWorks(page, "#/other", MATERIALS);
    return listFakeFiles(page, `${SET}/`);
  })();
  await page.locator('[data-screen="materials"]').click();
  await page.locator(".materials-work", { hasText: "灯台守の手紙_確認用" }).click();
  await page.locator(".materials-row", { hasText: "灯台に住む姉" }).click();
  const detail = page.locator(".materials-detail");
  await expect(detail.locator("h2")).toHaveText("姉");
  await expect(detail.locator("dt")).toContainText(["紹介", "性格", "登場話", "作者メモ"]);
  await expect(detail).toContainText("灯台に住む姉");
  await expect(detail).toContainText("妹には甘い");
  // 作者だけが書く欄には「作者」の印
  await expect(detail.locator("dt", { hasText: "作者メモ" }).locator(".flag")).toHaveText("作者");
  await expect(detail.locator("dt", { hasText: "紹介" }).locator(".flag")).toHaveCount(0);
  await expect(detail).not.toContainText("ane");
  await pressBack(page);
  await expect(page.locator(".materials-detail")).toHaveCount(0);
  await expect(page.locator(".materials-row", { hasText: "灯台に住む姉" })).toBeVisible();

  await page.locator(".materials-row", { hasText: "銀の懐中時計" }).click();
  await expect(page.locator(".materials-detail")).toContainText("父の形見");
  await expect(page.locator(".materials-detail")).toContainText("未回収");

  expect(await listFakeFiles(page, `${SET}/`)).toEqual(before);
  expect(await readFakeFile(page, `${SET}/characters/char_009.json`)).toBe("{ こわれている");
});

test("資料の無い作品：何も無いと言う。知らない作品・種類・id の道は作品を選ぶ所へ", async ({ page }) => {
  await openWithWorks(page, "#/other", MATERIALS);
  await page.locator('[data-screen="materials"]').click();
  await page.locator(".materials-work", { hasText: "雨の駅" }).click();
  await expect(page.locator(".materials-empty")).toHaveText("この作品には、まだ設定資料がありません");
  await page.evaluate(() => (location.hash = `#/materials/${encodeURIComponent("灯台守_確認用")}/character/${encodeURIComponent("../../本文")}`));
  await expect(page.locator(".materials-detail")).toHaveCount(0);
  await expect(page.locator(".materials-missing")).toHaveText("この資料は見つかりませんでした");
  await page.evaluate(() => (location.hash = `#/materials/${encodeURIComponent("../外")}`));
  await expect(page.locator(".materials-work").first()).toBeVisible();
});

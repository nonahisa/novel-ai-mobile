import { expect, test, type Page } from "@playwright/test";
import { FAKE_WORKS, openWithWorks, readFakeFile } from "./support/fakeWorks";

/**
 * **色の付いた名前を押したときの札**（設計書 5.7【決定】2026-11-15 作者「下に小さい札だけ出す」。`src/app/episodeScreen.ts`）。
 * 名前を押すと原稿の下に札だけが出て、資料はすぐには開かない。札を押すと紹介を出す。作品は作り物（`_確認用`）だけ
 */

/** 本体の `emptyCharacter` と同じ形の人物（e2e からは本体の部品を読めないので、形を写す） */
const character = (id: string, name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.1","aliases":[],"distinctFrom":[],"reading":null,"romaji":null,"icon":null,"iconSource":"none","summary":null,"gender":null,"affiliation":null,"role":null,"personality":null,"personalityFacets":[],"speechStyle":null,"speechStyleFacets":[],"appearance":null,"physical":null,"firstPerson":{"default":null,"variants":[]},"defaultSecondPerson":null,"addressTerms":[],"relations":[],"rejectedRelations":[],"abilities":[],"appearedChapters":[],"status":"登場済み","spoilerLevel":"public","authorNotes":"","exportNote":"","autoGenerated":true,"isMob":false,"evidence":null,"conflicts":[],"changes":[],"aiNotes":[],"customFields":{},"updatedAt":""}, id, name, ...extra });

const SISTER = character("char_001", "姉", { summary: "灯台に住む姉" });
const WITH_TERMS = { ...FAKE_WORKS, "灯台守_確認用/設定/characters/char_001.json": SISTER };
const pressBack = (page: Page) => page.evaluate(() => document.dispatchEvent(new Event("backbutton")));

async function openEpisode(page: Page, line: "right" | "left-colors"): Promise<void> {
  await openWithWorks(page, "#/display", WITH_TERMS);
  if (line === "right") await page.locator('[data-line="right"]').click();
  else await page.locator('[data-term-colors="on"]').click();
  await page.evaluate(() => (location.hash = "#/works"));
  await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
  await page.locator(".ep-list .ep").first().click();
  await expect(page.locator("#msEditor")).toBeVisible();
}

test.describe("色の付いた名前を押したときの札", () => {
  test("右の線の欄：名前を押すと札だけが出る。札を押すと紹介が出て、［戻る］キーで閉じても原稿にとどまる", async ({ page }) => {
    await openEpisode(page, "right");
    const editor = page.locator("#msEditor");
    const tag = page.locator("#termTag");
    const sheet = page.locator("#termSheet");
    await expect(editor.locator(".term-character")).toHaveCount(1);
    await expect(tag).toBeHidden();

    await editor.locator(".term-character").click();
    await expect(tag).toBeVisible();
    await expect(tag).toHaveText("姉（人物） ›");
    // 名前を押してすぐには資料を開かない（カーソルを置くつもりで押しても、原稿が隠れない）
    await expect(sheet).toBeHidden();

    await tag.click();
    await expect(sheet).toBeVisible();
    await expect(sheet.locator("h2")).toHaveText("姉（人物）");
    await expect(sheet).toContainText("灯台に住む姉");
    await pressBack(page);
    await expect(sheet).toBeHidden();
    await expect(page).toHaveURL(/#\/episode\//);

    // 名前でない所を押すと札は消える
    await editor.locator("[data-i]").nth(5).click();
    await expect(tag).toBeHidden();
    expect(await readFakeFile(page, "灯台守_確認用/設定/characters/char_001.json")).toBe(SISTER);
  });

  test("左の線の欄（用語の色を付ける・テスト中）：名前を押すと札が出て、打つと消える。［閉じる］で紹介を閉じる", async ({ page }) => {
    await openEpisode(page, "left-colors");
    const tag = page.locator("#termTag");
    const name = page.locator(".ms-backdrop .term-character");
    await expect(name).toHaveCount(1);
    // 裏の層は描き直すと span を作り直すので、位置は1回の evaluate で測る
    const box = await page.evaluate(() => {
      const r = document.querySelector(".ms-backdrop .term-character")!.getBoundingClientRect();
      return { x: r.x, y: r.y, width: r.width, height: r.height };
    });
    // 欄（透明な textarea）が上にあるので、名前の字の上を押す
    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
    await expect(tag).toHaveText("姉（人物） ›");
    await tag.click();
    await expect(page.locator("#termSheet")).toContainText("灯台に住む姉");
    await page.locator("#termSheetClose").click();
    await expect(page.locator("#termSheet")).toBeHidden();

    await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2);
    await expect(tag).toBeVisible();
    await page.keyboard.type("a");
    await expect(tag).toBeHidden();
  });

  test("色を付けない左の線の欄（既定）では札を出さない", async ({ page }) => {
    await openWithWorks(page, "#/works", WITH_TERMS);
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator(".ep-list .ep").first().click();
    const editor = page.locator("textarea#msEditor");
    await editor.click();
    await editor.evaluate((el: HTMLTextAreaElement) => el.setSelectionRange(1, 1));
    await editor.click({ position: { x: 20, y: 20 } });
    await expect(page.locator("#termTag")).toBeHidden();
  });

  test("札を押すと、その名前が出る話と行が並び、押すとその話のその字へ飛ぶ（保存してから移る）", async ({ page }) => {
    const third = ["霧が出た。", "姉は灯台にいた。"].join("\n");
    await openWithWorks(page, "#/display", { ...WITH_TERMS, "灯台守_確認用/本文/第3話 霧笛.txt": third });
    await page.locator('[data-term-colors="on"]').click();
    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator(".ep-list .ep").first().click();
    const editor = page.locator("textarea#msEditor");
    await expect(page.locator(".ms-backdrop .term-character")).toHaveCount(1);
    // 保存前の書きかけも探す
    await editor.evaluate((el: HTMLTextAreaElement) => el.setSelectionRange(el.value.length, el.value.length));
    await editor.focus();
    await page.keyboard.type("姉");
    const box = await page.evaluate(() => {
      const r = document.querySelector(".ms-backdrop .term-character")!.getBoundingClientRect();
      return { x: r.x + r.width / 2, y: r.y + r.height / 2 };
    });
    await page.mouse.click(box.x, box.y);
    await page.locator("#termTag").click();
    const hits = page.locator("#termSheetHits button");
    await expect(hits).toHaveCount(3);
    await expect(hits.nth(0)).toContainText("第1話 手紙・1行");
    await expect(hits.nth(1)).toContainText("第1話 手紙・3行");
    await expect(hits.nth(2)).toContainText("第3話 霧笛・2行");
    await expect(hits.nth(2)).toContainText("姉は灯台にいた。");

    await hits.nth(2).click();
    await expect(page).toHaveURL(/%E7%AC%AC3%E8%A9%B1/);
    await expect(page.locator("#termSheet")).toBeHidden();
    const next = page.locator("textarea#msEditor");
    await expect(next).toHaveValue(third);
    await expect.poll(() => next.evaluate((el: HTMLTextAreaElement) => el.selectionStart)).toBe(third.indexOf("姉"));
    // 離れる前に、書きかけは保存してある
    expect(await readFakeFile(page, "灯台守_確認用/本文/第1話 手紙.txt")).toContain(["直す", "姉"].join("\n"));
  });
});

/**
 * **右の線の欄の「見えない受け口」の作り**（iOS の WKWebView と AQUOS の WebView はこちら。EditContext が無い）。
 * 2026-11-18 作者の案 D「iPad で確かめてから、右の欄で範囲を選べるようにする」の下ごしらえ：パソコンの Chromium でも
 * EditContext を隠して、受け口の作りで色・札・紹介・飛ぶ・変換中の扱いを見張る（AQUOS 0.1.79 で同じ6つが通った）
 */
test.describe("右の線の欄（見えない受け口の作り）", () => {
  test.beforeEach(async ({ page }) => {
    await page.addInitScript(() => {
      delete (window as unknown as { EditContext?: unknown }).EditContext;
    });
  });

  test("名前を押すと札、札を押すと紹介と行、行を押すとその話へ。打ち込みは受け口で受ける", async ({ page }) => {
    const third = ["霧が出た。", "姉は灯台にいた。"].join(String.fromCharCode(10));
    await openWithWorks(page, "#/display", { ...WITH_TERMS, "灯台守_確認用/本文/第3話 霧笛.txt": third });
    await page.locator('[data-line="right"]').click();
    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator(".ep-list .ep").first().click();
    const editor = page.locator("#msEditor");
    await expect(editor).toBeVisible();
    // 受け口の作りで開いている（EditContext の作りではない）
    expect(await page.evaluate(() => "EditContext" in window)).toBe(false);
    await expect(editor.locator(".term-character")).toHaveCount(1);

    await editor.locator(".term-character").click();
    const tag = page.locator("#termTag");
    await expect(tag).toHaveText("姉（人物） ›");
    await tag.click();
    const hits = page.locator("#termSheetHits button");
    await expect(hits).toHaveCount(2);
    await hits.nth(1).click();
    await expect(page).toHaveURL(/%E7%AC%AC3%E8%A9%B1/);
    await expect(page.locator("#termSheet")).toBeHidden();
    await expect(page.locator("#msEditor .term-character")).toHaveCount(1);
  });

  test("名前のすぐ後ろで打つと札は消え、名前の色は残る。そのあと名前を押すとまた札", async ({ page }) => {
    await openWithWorks(page, "#/display", WITH_TERMS);
    await page.locator('[data-line="right"]').click();
    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator(".ep-list .ep").first().click();
    const editor = page.locator("#msEditor");
    await editor.locator(".term-character").click();
    await expect(page.locator("#termTag")).toBeVisible();
    await page.keyboard.type("a");
    await expect(page.locator("#termTag")).toBeHidden();
    await expect(editor).toContainText("a");
    await expect(editor.locator(".term-character")).toHaveText("姉");
    await editor.locator(".term-character").click();
    await expect(page.locator("#termTag")).toHaveText("姉（人物） ›");
  });

  test.fixme("範囲を選べる（長押し・つまみ）。選んだ字にルビ・傍点を振れる（案 D。iPad で1〜6が通ってから作る）", async () => {});
});


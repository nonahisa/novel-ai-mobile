/**
 * **設定資料の1件を、本文から読み直す**（設計書 4.4.1「設定資料の1件 → 本文から読み直す」。2026-11-22 作者の答え
 * 「本文から読み直すまで作る」。本体の設定資料パネルの［AIで再読込］〈設計書 6.31〉と同じ仕組み）。
 *
 * 本体と同じところ（部品は全部本体のもの。写しを作らない）：
 * - 頼みの文・答えの形・揺らし（`buildEnrichPrompt`・`buildEnrichSchema`・`SETTINGS_ENRICH_TEMPERATURE`・
 *   `SETTINGS_ASSISTANT_SYSTEM_PROMPT`）。【現在の設定】は `describeEnrichTarget`（留意点があれば変化の記録を渡さない）
 * - 本文の抜粋：話ごとの出典（`excerptSourcesOfEpisode`。合本は中の話へ割る・メモは消す）から、名前の出る場面を
 *   作品全体から均等に、合計12,000字まで（`collectMentionExcerpts`・`searchTermsFor`・`otherRecordNamesFor`）
 * - 語り手の断り（対象が主人公で、抜粋にほかの語り手の場面が入るときだけ。`enrichForeignNarratorOf`）
 * - 検算（`checkEnrichProposals`：字数・口調の写し・台詞に無い一人称・作品に無い話・名前の出ない話の変化の持ち越し）と、
 *   はじいた記述の照合（`parseMisattributedValues`）
 * - 反映（`apply*Edits`。`authorConfirmed: false` なので、AI の案を採っても「作者の資料」の印は付けない）。書く形は本体の
 *   保存と同じ（2字下げ・`updatedAt` を今に・元の改行と文字コードのまま）
 *
 * 本体と違うところ：
 * - 本文の抜粋の前に検索（BM25・意味検索）を使わない（本体の MCP 版と同じ。検索語づくりの AI の1回もかからない）
 * - 作者の資料（`autoGenerated: false`）の、書かれている欄は案に出さない（本体の MCP 版と同じ。パソコンの画面は、既定で
 *   選ばずに出す。2026-11-22 作者の答え「空いた欄だけ」）
 * - はじいた記述は、登場人物の読み直しのときだけ行き先を出して、押せば入れる（本体と同じ。`placeMisattributed`）。
 *   語り手の取り違えを移す案は、まだ作らない（本体の部品が vscode の側にあるため。core へ移す頼みは母艦へ出した）
 */

export type EnrichKind = SettingsKind;

const DIRECTORY: Record<EnrichKind, string> = {
  character: "characters",
  ability: "abilities",
  organization: "organizations",
  location: "locations",
  world: "world",
};

const PARSE: Record<EnrichKind, (raw: unknown) => EnrichRecord> = {
  character: parseCharacter,
  ability: parseAbility,
  organization: parseOrganization,
  location: parseLocation,
  world: parseWorldItem,
};

const SCHEMA_VERSION: Record<EnrichKind, string> = {
  character: CHARACTER_SCHEMA_VERSION,
  ability: ABILITY_SCHEMA_VERSION,
  organization: ORGANIZATION_SCHEMA_VERSION,
  location: LOCATION_SCHEMA_VERSION,
  world: WORLD_SCHEMA_VERSION,
};

export function isEnrichKind(kind: string): kind is EnrichKind {
  return Object.prototype.hasOwnProperty.call(DIRECTORY, kind);
}

/** 読んだ1件のファイル（書き戻すときの照らし合わせに、読んだときの中身を持つ） */
export interface RecordFile {
  kind: EnrichKind;
  record: EnrichRecord;
  /** 置き場の中の場所（一覧で見つけたファイル。道の id から作らない） */
  path: string;
  content: TextFileContent;
  /** ファイルの JSON そのもの（知らない欄があるかを見る） */
  raw: Record<string, unknown>;
}

/**
 * 種類のフォルダーから、その id の1件を読む。読み方は `readKind` と同じ（`_` で始まるファイルは読まない・ファイル名と id が
 * 合わなければ使わない）。**道の id からファイルの場所を作らない**（一覧で見つけたものだけ）
 */
export async function readRecordFile(store: FileStore, settingsDir: string, kind: EnrichKind, id: string): Promise<RecordFile | undefined> {
  const dir = joinStorePath(settingsDir, DIRECTORY[kind]);
  let names: string[];
  try {
    names = await store.listFiles(dir);
  } catch (error) {
    if (error instanceof FileNotFoundError) return undefined;
    throw error;
  }
  for (const name of [...names].sort()) {
    if (!name.endsWith(".json") || name.startsWith("_")) continue;
    if (name !== `${id}.json` && !name.startsWith(`${id}_`)) continue;
    const path = joinStorePath(dir, name);
    const content = await readTextFile(store, path);
    let raw: unknown;
    let record: EnrichRecord;
    try {
      raw = JSON.parse(content.text);
      record = PARSE[kind](raw);
    } catch (error) {
      // 一覧を出したあとで壊れた・書き換わった。訳は日本語で（`readErrorMessage`）
      throw new Error(`${DIRECTORY[kind]}/${name} を読めませんでした：${readErrorMessage(error)}`);
    }
    if (record.id !== id) continue;
    return { kind, record, path, content, raw: raw as Record<string, unknown> };
  }
  return undefined;
}

/** 読み直しの材料（走らせる前にそろえる。見積もりの字数もここから） */
export interface EnrichMaterial {
  target: RecordFile;
  characters: Character[];
  customFields: CustomFieldDefinition[];
  sources: ExcerptSource[];
  excerpts: MentionExcerpt[];
  knownChapters: Set<number>;
  system: string;
  prompt: string;
  schema: object;
  /** 本文の抜粋の字数（見積もりに出す） */
  excerptChars: number;
  notes: string;
}

export interface PrepareEnrichInput {
  store: FileStore;
  work: ScannedWork;
  settingsDir: string;
  memoMarkers: MemoMarkers;
  kind: EnrichKind;
  id: string;
  /** 作者の留意点（原文のまま渡す。空なら項目の充実） */
  notes: string;
  /** 同期で競合したまま選んでいない話（置き場の中の場所）。その話の本文は渡さない */
  undecidedConflicts?: ReadonlySet<string>;
}

/** 各話あらすじの本文（読めなければ空。本体と同じく、関与度の加点が付かないだけで止めない） */
async function synopsisTexts(store: FileStore, settingsDir: string): Promise<string[]> {
  try {
    return (await loadSynopses(store, settingsDir)).set.episodes.map((episode) => episode.synopsis.trim()).filter((text) => text.length > 0);
  } catch {
    return [];
  }
}

/** 能力の体系（本体と同じく、無ければ既定・壊れていれば添えない） */
async function abilitySystemOf(store: FileStore, settingsDir: string): Promise<AbilitySystem | undefined> {
  try {
    const content = await readTextFile(store, joinStorePath(settingsDir, "ability_system.json"));
    return parseAbilitySystem(JSON.parse(content.text));
  } catch (error) {
    if (error instanceof FileNotFoundError) return emptyAbilitySystem();
    return undefined;
  }
}

/** 作品の本文を話ごとの出典にする（本体の `loadExcerptSources` と同じ割り方。競合の印のある話・選んでいない話は入れない） */
export async function excerptSourcesOfWork(
  store: FileStore,
  work: ScannedWork,
  memoMarkers: MemoMarkers,
  undecided: ReadonlySet<string> = new Set()
): Promise<ExcerptSource[]> {
  const sources: ExcerptSource[] = [];
  for (const episode of work.episodes) {
    const path = toStorePath(episode.filePath);
    if (!path || episode.hasConflictMarkers === true || undecided.has(path)) continue;
    const text = (await readTextFile(store, path)).text;
    if (containsConflictMarkers(text)) continue;
    sources.push(...excerptSourcesOfEpisode(episode, text.replace(/\r\n?/g, "\n"), memoMarkers));
  }
  return sources;
}

export async function prepareEnrich(input: PrepareEnrichInput): Promise<EnrichMaterial> {
  const { store, settingsDir, kind } = input;
  const target = await readRecordFile(store, settingsDir, kind, input.id);
  if (!target) throw new Error("この資料は見つかりませんでした");
  const ignored: { file: string; message: string }[] = [];
  const characters = await readKind(store, settingsDir, "characters", parseCharacter, ignored);
  const others = [
    ...characters,
    ...(await readKind(store, settingsDir, "abilities", parseAbility, ignored)),
    ...(await readKind(store, settingsDir, "locations", parseLocation, ignored)),
    ...(await readKind(store, settingsDir, "organizations", parseOrganization, ignored)),
  ];
  const customSet = await readCustomFieldSet(store, settingsDir, ignored);
  const customFields = customSet ? fieldsFor(customSet, "character") : [];
  const sources = await excerptSourcesOfWork(store, input.work, input.memoMarkers, input.undecidedConflicts);
  const record = target.record;
  const excerpts = collectMentionExcerpts(sources, searchTermsFor(kind, record, characters), { otherNames: otherRecordNamesFor(record, others) });
  const notes = input.notes.trim();
  const narration =
    kind === "character" ? workNarratorContextOf(sources.map((source) => blankMemoLines(source.text, input.memoMarkers)).join("\n"), characters) : null;
  const prompt = buildEnrichPrompt({
    workTitle: input.work.title,
    kind,
    target: {
      kindLabel: KIND_LABELS[kind],
      name: record.name,
      currentSettings: describeEnrichTarget(kind, record, {
        customFields,
        abilitySystem: kind === "ability" ? await abilitySystemOf(store, settingsDir) : undefined,
        characters,
        notes,
        synopses: kind === "character" ? await synopsisTexts(store, settingsDir) : undefined,
        people: characters,
      }),
    },
    excerpts,
    customFields,
    notes,
    foreignNarrator: narration ? enrichForeignNarratorOf(record, excerpts, sources, narration) : null,
  });
  return {
    target,
    characters,
    customFields,
    sources,
    excerpts,
    knownChapters: knownChaptersOf(input.work.episodes),
    system: SETTINGS_ASSISTANT_SYSTEM_PROMPT,
    prompt,
    schema: buildEnrichSchema(kind, customFields),
    excerptChars: excerpts.reduce((total, excerpt) => total + excerpt.text.length, 0),
    notes,
  };
}

/** 作者に見せる案の1行 */
export interface EnrichRow {
  /** 反映するときの鍵（作者が足した項目は `custom:` を付ける。本体の画面と同じ） */
  key: string;
  label: string;
  before: string;
  after: string;
  fillsBlank: boolean;
  multiline: boolean;
}

export interface EnrichOutcome {
  rows: EnrichRow[];
  /** 作者の資料の書かれた欄なので、案に出さなかった項目（見出しと案） */
  heldBack: { label: string; after: string }[];
  /** 検算で落とした訳（作者に見せる短い文） */
  dropped: string[];
  /**
   * はじいた記述（この記録のものではない、と AI が判断したもの。本文と照合できたものだけ）。
   * `destination` は登場人物の読み直しのときだけ（本体と同じく、行き先は人物の資料。決めるのはコード）
   */
  misattributed: MisattributedItem[];
}

export type MisattributedItem = MisattributedValue & { fieldLabel: string; destination?: MisattributedDestination };

/**
 * AI に頼んで、答えを検算し、案にする。**書かない。**
 *
 * @param protectAuthorValues 作者の資料（`autoGenerated: false`）の書かれた欄は案に出さない（本体の MCP 版と同じ。既定）。
 *   false なら本体の画面と同じく出す（既定で選ぶのは空欄を埋める案だけ）
 */
export async function runEnrich(material: EnrichMaterial, call: ModelCall, options: { signal?: AbortSignal; protectAuthorValues?: boolean } = {}): Promise<EnrichOutcome> {
  const { kind, record } = material.target;
  const text = await call({
    system: material.system,
    user: material.prompt,
    schema: material.schema,
    temperature: SETTINGS_ENRICH_TEMPERATURE,
    ...(options.signal ? { signal: options.signal } : {}),
  });
  const parsed = parseEnrichResult(text);
  if (!parsed) throw new Error("AI の答えが読めませんでした");
  const excerptText = material.excerpts.map((excerpt) => excerpt.text).join("\n");
  const checked = checkEnrichProposals({
    kind,
    record,
    customFields: material.customFields,
    parsed,
    excerptText,
    knownChapters: material.knownChapters,
    ...(kind === "character" ? { sources: material.sources } : {}),
  });
  const protect = options.protectAuthorValues ?? true;
  const rows: EnrichRow[] = [];
  const heldBack: EnrichOutcome["heldBack"] = [];
  for (const proposal of checked.proposals) {
    if (protect && !record.autoGenerated && proposal.before.length > 0) {
      heldBack.push({ label: proposal.field.label, after: proposal.after });
      continue;
    }
    rows.push(rowOf(proposal));
  }
  const dropped: string[] = [];
  for (const item of checked.unknownCitations) dropped.push(`${item.label}：作品に無い話（第${item.chapters.join("・")}話）を挙げていたので外しました`);
  if (checked.speechEchoes > 0) dropped.push("口調：頼みの言葉の写しだったので外しました");
  if (checked.speechUnspokenFirstPersons.length > 0) dropped.push(`口調：一人称「${checked.speechUnspokenFirstPersons.join("・")}」が本文の台詞に無いので外しました`);
  for (const item of checked.foreignChanges) dropped.push(`${item.label}：名前の出ない話の記録から持ち越した語（${item.phrases.join("・")}）があったので外しました`);
  // 見出しは本体の項目の並びから引く（案の出なかった項目も、はじいた記述には出る。本体の MCP 版と同じ）
  const labels = new Map(enrichableFields(kind, material.customFields).map((field) => [field.key, field.label]));
  const misattributed = parseMisattributedValues(parsed[MISATTRIBUTED_KEY], excerptText, misattributedAllowedFields(kind, material.customFields)).entries.map(
    (entry): MisattributedItem => ({
      ...entry,
      fieldLabel: labels.get(entry.field) ?? entry.field,
      ...(kind === "character" ? { destination: resolveMisattributedDestination(entry.belongsTo, material.characters) } : {}),
    })
  );
  return { rows, heldBack, dropped, misattributed };
}

function rowOf(proposal: EnrichProposal): EnrichRow {
  return {
    key: proposal.field.custom ? `custom:${proposal.field.key}` : proposal.field.key,
    label: proposal.field.label,
    before: proposal.before,
    after: proposal.after,
    fillsBlank: proposal.fillsBlank,
    multiline: proposal.field.multiline === true,
  };
}

/** 選んだ案を記録に当てる（本体の `apply*Edits`。AI の案なので `authorConfirmed: false`） */
export function applyEnrichRows(target: RecordFile, chosen: Record<string, string>, characters: readonly Character[], now: string): EnrichRecord {
  const edits = toRecordEdits(chosen);
  const options = { authorConfirmed: false, characters, now };
  switch (target.kind) {
    case "character":
      return applyCharacterEdits(target.record as Character, edits, options);
    case "ability":
      return applyAbilityEdits(target.record as Parameters<typeof applyAbilityEdits>[0], edits, options);
    case "organization":
      return applyOrganizationEdits(target.record as Parameters<typeof applyOrganizationEdits>[0], edits, options);
    case "location":
      return applyLocationEdits(target.record as Parameters<typeof applyLocationEdits>[0], edits, options);
    case "world":
      return applyWorldItemEdits(target.record as Parameters<typeof applyWorldItemEdits>[0], edits, options);
  }
}

export type SaveRecordResult =
  | { ok: true; recoveryPath?: string }
  | { ok: false; reason: WriteTextFailureReason | "newer_shape" | "unknown_fields"; detail?: string };

/**
 * 記録を書き戻す。本体の保存と同じ形（2字下げ・末に改行・`updatedAt` を今に）で、元の改行・文字コードのまま、読んだときの
 * 中身と照らし合わせてから（外で変わっていれば書かない）、元を退避して書く。
 *
 * - モバイル版の知らない新しい形（`schemaVersion` が新しい）なら書かない
 * - ファイルに、モバイル版の読み方では落ちる欄があれば書かない（パソコンの新しい版で足された欄を、同期で消さない）
 */
export async function saveRecord(store: FileStore, target: RecordFile, record: EnrichRecord, now: string): Promise<SaveRecordResult> {
  const label = `${KIND_LABELS[target.kind]}の資料`;
  const newer = ledgerShapeProblem(label, target.content.text, SCHEMA_VERSION[target.kind]);
  if (newer) return { ok: false, reason: "newer_shape", detail: newer };
  const known = new Set(Object.keys(record));
  const unknown = Object.keys(target.raw).filter((key) => !known.has(key));
  if (unknown.length > 0) {
    return {
      ok: false,
      reason: "unknown_fields",
      detail: `この資料には、モバイル版の知らない欄（${unknown.join("・")}）があるので書きませんでした。パソコンで反映してください`,
    };
  }
  const text = `${JSON.stringify({ ...record, updatedAt: now }, null, 2)}\n`;
  const written = await writeTextFilePreservingFormat(store, target.path, text, target.content, target.content.hash);
  if (!written.ok) return { ok: false, reason: written.reason, ...(written.detail !== undefined ? { detail: written.detail } : {}) };
  return { ok: true, ...(written.recoveryPath ? { recoveryPath: written.recoveryPath } : {}) };
}

/** 書けなかったときに作者へ出す一言 */
export function saveRecordFailureText(result: Extract<SaveRecordResult, { ok: false }>): string {
  if ((result.reason === "newer_shape" || result.reason === "unknown_fields") && result.detail) return result.detail;
  return result.reason === "modified_externally"
    ? "読んだあとで資料のファイルが変わったので、書きませんでした（同期のあとでもう一度）"
    : "資料のファイルに書けませんでした";
}

export type PlaceMisattributedResult =
  | { ok: true; notice: string; destination: MisattributedDestination; path?: string }
  | { ok: false; notice: string };

/**
 * **はじいた記述を、行き先の人物の資料へ入れる**（本体の設定資料パネルの「はじいた記述の行き先」と同じ。設計書 6.31.2）。
 * 押されたときだけ呼ぶ。ここが、はじいた記述がファイルへ入る唯一の所。
 *
 * - 行き先は押したときの資料で引き直す（`resolveMisattributedDestination`。先に同じ相手を新しく起こしていれば、そちらへ入る）
 * - 既にいる人物：上書きしない。空欄なら埋め、値があって食い違えば「変化かもしれない」として残す（`insertMisattributedValue`）。
 *   書き方は反映と同じ（`saveRecord`：外で変わっていれば書かない・知らない欄があれば書かない）
 * - 見つからない：その値だけを持つ人物を起こす（`planMisattributedRecord`。ファイル名は本体と同じ `characterFileName`、
 *   新しいファイルの形も本体と同じ）。同じ id のファイルが在れば書かない
 */
export async function placeMisattributed(
  store: FileStore,
  settingsDir: string,
  entry: MisattributedValue,
  now: string,
  beforeWrite?: (path: string) => Promise<void>
): Promise<PlaceMisattributedResult> {
  const characters = await readKind(store, settingsDir, DIRECTORY.character, parseCharacter, []);
  const destination = resolveMisattributedDestination(entry.belongsTo, characters);
  if (destination.kind === "existing") {
    const file = await readRecordFile(store, settingsDir, "character", destination.id);
    if (!file) return { ok: false, notice: `「${destination.name}」が見つかりません。パソコンで消されたのかもしれません` };
    const result = insertMisattributedValue(file.record as Character, entry);
    if (!result.changed) return { ok: true, notice: `「${destination.name}」には、同じ内容が既に入っていました`, destination };
    await beforeWrite?.(file.path).catch(() => undefined);
    const saved = await saveRecord(store, file, result.character, now);
    if (!saved.ok) return { ok: false, notice: saveRecordFailureText(saved) };
    return {
      ok: true,
      notice: result.conflicted
        ? `「${destination.name}」には既に別の値があったので、上書きせず「変化かもしれない」として残しました`
        : `「${destination.name}」の空いていた項目へ入れました`,
      destination,
      path: file.path,
    };
  }
  const created = planMisattributedRecord(entry, characters);
  const dir = joinStorePath(settingsDir, DIRECTORY.character);
  await store.createDirectory(dir);
  const names = await store.listFiles(dir);
  if (names.some((name) => name === `${created.id}.json` || name.startsWith(`${created.id}_`))) {
    return { ok: false, notice: "同じ番号の人物の資料が既にあるので、書きませんでした（同期のあとでもう一度）" };
  }
  const path = joinStorePath(dir, characterFileName(created));
  await beforeWrite?.(path).catch(() => undefined);
  try {
    await store.writeFile(path, new TextEncoder().encode(formatJsonForFile({ ...created, updatedAt: now }, NEW_JSON_FILE_FORMAT)), { mode: "create" });
  } catch {
    // 読んだあとで同じ名前のファイルができた。黙って上書きしない
    return { ok: false, notice: "同じ名前の資料のファイルが既にあるので、書きませんでした" };
  }
  return {
    ok: true,
    notice: `「${created.name}」を新しく起こしました。中身はこの1項目だけなので、パソコンで「設定資料を抽出」すると本文から入ります`,
    destination,
    path,
  };
}

/** 行き先を、いまの資料で引き直す（入れたあとに。新しく起こした人物へ、同じ相手の2件目が「新しく起こす」で並ばないように。本体と同じ） */
export async function refreshDestinations(store: FileStore, settingsDir: string, items: readonly MisattributedItem[]): Promise<MisattributedItem[]> {
  const characters = await readKind(store, settingsDir, DIRECTORY.character, parseCharacter, []);
  return items.map((item) => (item.destination ? { ...item, destination: resolveMisattributedDestination(item.belongsTo, characters) } : item));
}

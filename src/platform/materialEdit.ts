/**
 * **設定資料の1件を手で直す**（［設定資料］→ 1件 →［直す］。2026-11-27 作者の答え「全部の欄」）。
 *
 * - 欄の並びと見出しは本体の設定資料パネル（`features/settingsPanel.ts` の `detailOf`）と同じ。作者が足した項目
 *   （`custom_fields.json`）は既定の項目のあと・作者メモの前
 * - 反映は本体の `apply*Edits`（作者が直したので `authorConfirmed` は既定のまま。`autoGenerated` が false になり、
 *   以後の抽出が上書きしない。本体の実装ルール2）。**変えた欄だけを渡す**——触らなかった作者メモ・資料用の補足・
 *   作者が足した項目・主人公の印などは、渡さないので本体の部品が触らない
 * - 書き戻しは読み直しと同じ `saveRecord`（読んだときの中身と照らし合わせ、外で変わっていれば書かない・知らない欄や
 *   新しい形の資料には書かない・元の改行と文字コードのまま）
 * - 名前を変えても、ファイルは同じ場所に書く（ファイル名は id で始まるので読める。消して作り直すと、同期で
 *   パソコンの側の変更とぶつかったときに戻せない。ファイル名はパソコンで次に保存したときに本体が付け直す）
 */

export interface EditField {
  /** 本体の `RecordEdits` の鍵（作者が足した項目は `custom:<key>`） */
  key: string;
  label: string;
  value: string;
  multiline: boolean;
  /** チェックの欄（値は "1" か ""） */
  check?: true;
  /** 決まった値から選ぶ欄 */
  choices?: { value: string; label: string }[];
  hint?: string;
}

const text = (key: string, label: string, value: string | null | undefined, multiline = false): EditField => ({ key, label, value: value ?? "", multiline });
const check = (key: string, label: string, on: boolean): EditField => ({ key, label, value: on ? "1" : "", multiline: false, check: true });

const SUMMARY_LABEL = `紹介（${SUMMARY_MAX_CHARS}字以内）`;
const ALIAS_READINGS_LABEL = "別名の読み（1行に1つ「別名=読み」）";
const DWELLINGS_HINT = "例：「体の持ち主=第4話〜：補足」。範囲と補足は省けます";
const RELATIONS_HINT = "1行に1つ「相手=関係」。消した関係は「退けた関係」として残り、次の抽出で戻りません";

type Record5 = EnrichRecord & { aliases: string[]; authorNotes: string; exportNote: string; customFields?: Record<string, string> };

/** その1件の直せる欄（本体のパネルと同じ並び） */
export async function editFieldsOf(store: FileStore, settingsDir: string, file: RecordFile): Promise<EditField[]> {
  const customSet = await readCustomFieldSet(store, settingsDir, []);
  const record = file.record as Record5;
  const custom = (customSet ? fieldsFor(customSet, file.kind) : []).map((definition) =>
    text(`${CUSTOM_FIELD_PREFIX}${definition.key}`, definition.label, record.customFields?.[definition.key], definition.multiline)
  );
  const notes = [text("authorNotes", "作者メモ", record.authorNotes, true), text("exportNote", "資料用の補足", record.exportNote, true)];
  const head = (nameLabel = "名前", readingLabel = "読み", aliasesLabel = "別名（読点区切り）") => ({
    name: text("name", nameLabel, record.name),
    reading: text("reading", readingLabel, (record as { reading: string | null }).reading),
    aliases: text("aliases", aliasesLabel, record.aliases.join("、")),
    aliasReadings: text("aliasReadings", ALIAS_READINGS_LABEL, formatAliasReadingsForEdit(record as Parameters<typeof formatAliasReadingsForEdit>[0]), true),
  });
  switch (file.kind) {
    case "character": {
      const person = file.record as Character;
      const h = head();
      return [
        h.name,
        text("summary", SUMMARY_LABEL, person.summary, true),
        text("gender", "性別", person.gender),
        text("affiliation", "所属", person.affiliation),
        h.reading,
        h.aliases,
        h.aliasReadings,
        text("role", "役割", person.role),
        text("personality", "性格", person.personality, true),
        text("speechStyle", "口調", person.speechStyle ?? null, true),
        text("appearance", "外見", person.appearance, true),
        { ...text("relations", "関係（1行に1つ「相手=関係」）", formatRelationsForEdit(person.relations), true), hint: RELATIONS_HINT },
        check("isMob", "モブ・集団として扱う（一覧の下へまとめ、色と辞書から外す）", person.isMob),
        check("isProtagonist", "主人公（中心人物）として扱う", person.isProtagonist === true),
        {
          ...text("dwellings", "心と体が別の人物（1行に1つ「体の持ち主=第4話〜第16話：補足」）", formatDwellingsForEdit(person.dwellings), true),
          hint: DWELLINGS_HINT,
        },
        ...custom,
        ...notes,
      ];
    }
    case "ability": {
      const ability = file.record as Extract<EnrichRecord, { cost: unknown }>;
      const h = head();
      return [
        h.name,
        text("summary", SUMMARY_LABEL, ability.summary, true),
        h.reading,
        h.aliases,
        h.aliasReadings,
        text("category", "分類", ability.category),
        text("description", "説明", ability.description, true),
        text("cost", "代償", ability.cost, true),
        text("limitation", "制約", ability.limitation, true),
        ...custom,
        ...notes,
      ];
    }
    case "organization": {
      const organization = file.record as Extract<EnrichRecord, { parent: unknown }>;
      const h = head();
      return [
        h.name,
        text("summary", SUMMARY_LABEL, organization.summary, true),
        h.reading,
        h.aliases,
        h.aliasReadings,
        text("category", "種別", organization.category),
        text("parent", "上位組織", organization.parent),
        text("description", "説明", organization.description, true),
        ...custom,
        ...notes,
      ];
    }
    case "location": {
      const place = file.record as Location;
      const h = head();
      return [
        h.name,
        text("summary", SUMMARY_LABEL, place.summary, true),
        h.reading,
        h.aliases,
        h.aliasReadings,
        text("region", "地域", place.region),
        { ...text("relations", "位置関係（1行に1つ）", formatLocationRelationsForEdit(place.relations ?? []), true), hint: describeLocationRelationEditHint() },
        text("description", "説明", place.description, true),
        ...custom,
        ...notes,
      ];
    }
    case "world": {
      const item = file.record as Extract<EnrichRecord, { category: string }> & { description: string | null };
      const h = head("見出し（15字以内）", "読み（固有の用語のみ。辞書に使う）", "別の言い方（読点区切り）");
      return [
        h.name,
        {
          ...text("category", "分類", item.category),
          // 分類は決まった7種（自由に書くと、読み込みの検証で落ちる。本体と同じ）
          choices: WORLD_CATEGORIES.map((category) => ({ value: category, label: WORLD_CATEGORY_LABELS[category] })),
        },
        h.reading,
        h.aliases,
        h.aliasReadings,
        text("description", "内容", item.description, true),
        ...custom,
        ...notes,
      ];
    }
  }
}

/** 画面の値と、開いたときの値を比べて、変えた欄だけを返す（前後の空白だけの違いは変えたことにしない） */
export function changedValues(fields: readonly EditField[], now: Record<string, string>): Record<string, string> {
  const changed: Record<string, string> = {};
  for (const field of fields) {
    const value = now[field.key];
    if (value === undefined) continue;
    if (value.trim() !== field.value.trim()) changed[field.key] = value;
  }
  return changed;
}

export type SaveEditsResult = { ok: true; notice: string; recoveryPath?: string } | { ok: false; notice: string };

/**
 * 変えた欄を本体の部品で当てて書く。読めない行（関係・宿り）や空の名前は、本体と同じ訳で止める（黙って捨てない）。
 * 人物は顔ぶれを、場所は場所の一覧を渡す（関係を退けた記録・位置関係の相手の引き当て。本体のパネルと同じ）
 */
export async function saveMaterialEdits(
  store: FileStore,
  settingsDir: string,
  file: RecordFile,
  changed: Record<string, string>,
  now: string,
  beforeWrite?: (path: string) => Promise<void>
): Promise<SaveEditsResult> {
  const count = Object.keys(changed).length;
  if (count === 0) return { ok: false, notice: "変えた欄がありません" };
  const edits = toRecordEdits(changed);
  let updated: EnrichRecord;
  try {
    switch (file.kind) {
      case "character": {
        const characters = await readKind(store, settingsDir, "characters", parseCharacter, []);
        updated = applyCharacterEdits(file.record as Character, edits, { characters, now });
        break;
      }
      case "location": {
        const locations = await readKind(store, settingsDir, "locations", parseLocation, []);
        updated = applyLocationEdits(file.record as Location, edits, { locations, now });
        break;
      }
      case "ability":
        updated = applyAbilityEdits(file.record as Parameters<typeof applyAbilityEdits>[0], edits, { now });
        break;
      case "organization":
        updated = applyOrganizationEdits(file.record as Parameters<typeof applyOrganizationEdits>[0], edits, { now });
        break;
      case "world":
        updated = applyWorldItemEdits(file.record as Parameters<typeof applyWorldItemEdits>[0], edits, { now });
        break;
    }
  } catch (error) {
    if (error instanceof SettingsEditError) return { ok: false, notice: `${error.message}（書いていません）` };
    throw error;
  }
  await beforeWrite?.(file.path).catch(() => undefined);
  const saved = await saveRecord(store, file, updated, now);
  if (!saved.ok) return { ok: false, notice: saveRecordFailureText(saved) };
  return { ok: true, notice: `${count} 項目を保存しました`, ...(saved.recoveryPath ? { recoveryPath: saved.recoveryPath } : {}) };
}

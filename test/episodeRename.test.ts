import { describe, expect, test } from "vitest";
import { readingDictionaryFileName } from "../src/shared";
import { MemoryFileStore } from "../src/platform/memoryFileStore";
import { renameEpisodeWithLedgers, renamedEpisodeFileName } from "../src/platform/episodeRename";
import { journalPathFor } from "../src/app/draftJournal";

/**
 * **話のファイル名を変え、パスで話を指す台帳を付け替える**（2026-11-21 作者の答え「パソコンと同じにする」。本体の
 * `renameEpisodeFile`・`followEpisodeFileRenames` と同じ決まり）。作者の原稿と台帳を書く道なので、本文が1字も変わらないこと・
 * 付け替えられない台帳があれば名前を変えないことを見る。作品は作り物（`_確認用`）だけ
 */
const utf8 = (s: string) => new TextEncoder().encode(s);
const text = (store: MemoryFileStore, path: string) => {
  const bytes = store.peek(path);
  return bytes === undefined ? undefined : new TextDecoder().decode(bytes);
};
const json = (store: MemoryFileStore, path: string) => JSON.parse(text(store, path)!);
const ROOT = "灯台守_確認用";
const EP = `${ROOT}/本文/第5話.txt`;
const NEW = `${ROOT}/本文/第5話_灯台の朝.txt`;
const BODY = "霧の朝、姉の手紙を読み返した。\r\n// 付箋\r\n";

function work(extra: Record<string, string> = {}): MemoryFileStore {
  const store = new MemoryFileStore();
  const files: Record<string, string> = {
    [`${ROOT}/.aiwriter/config.json`]: '{"workTitle":"灯台守"}',
    [`${ROOT}/本文/第4話 港.txt`]: "港。",
    [EP]: BODY,
    ...extra,
  };
  for (const [path, content] of Object.entries(files)) store.putExternally(path, utf8(content));
  return store;
}

describe("名前", () => {
  test("元の名前に「_サブタイトル」を足す。ファイル名に使えない字は替える", () => {
    expect(renamedEpisodeFileName("第5話.txt", "灯台の朝")).toBe("第5話_灯台の朝.txt");
    expect(renamedEpisodeFileName("007.txt", "湖畔/誓い")).toBe("007_湖畔／誓い.txt");
    expect(renamedEpisodeFileName("第5話.txt", "  ")).toBeUndefined();
  });
});

describe("名前を変えて台帳を付け替える", () => {
  test("本文は1字も変えず、章立て・投稿状態（出し直しも）・年表・本の設計図・あらすじ・読みの辞書の指し先だけを付け替える。知らない欄は残す", async () => {
    const reading = `${ROOT}/.aiwriter/readings/${readingDictionaryFileName("本文/第5話.txt")}`;
    const store = work({
      [`${ROOT}/設定/章立て.json`]: JSON.stringify({ schemaVersion: "1", chapters: [{ name: "第二章", startEpisodePath: "本文/第5話.txt", note: "残す" }] }, null, 2),
      [`${ROOT}/設定/投稿状態.json`]: JSON.stringify({
        schemaVersion: "1",
        sites: [],
        posts: [{ site: "kakuyomu", episodePath: "本文/第5話.txt", bodyHash: "v3:abc" }, { site: "kakuyomu", episodePath: "本文/第4話 港.txt" }],
        revisions: [{ site: "kakuyomu", episodePath: "本文/第5話.txt" }],
        futureField: { keep: true },
      }),
      [`${ROOT}/設定/timeline.json`]: JSON.stringify({ schemaVersion: "0.1", episodes: [{ filePath: "本文/第5話.txt", at: "春" }] }),
      [`${ROOT}/設定/書籍/book.json`]: JSON.stringify({ schemaVersion: "0.1", illustrations: [{ episodePath: "本文/第5話.txt", line: 3 }], pageBreaks: [] }),
      [`${ROOT}/設定/chapter_synopses.json`]: JSON.stringify({ schemaVersion: "0.1", episodes: [{ chapter: 5, fileName: "第5話.txt", title: null, synopsis: "霧の朝", autoGenerated: true }] }),
      [reading]: JSON.stringify({ episode: "本文/第5話.txt", entries: [{ word: "霧笛", reading: "むてき" }] }),
    });
    const outcome = await renameEpisodeWithLedgers({ store, root: ROOT, path: EP, subtitle: "灯台の朝" });
    expect(outcome).toEqual({ ok: true, newPath: NEW, newFileName: "第5話_灯台の朝.txt", notes: [] });
    expect(text(store, EP)).toBeUndefined();
    expect(text(store, NEW)).toBe(BODY);

    expect(json(store, `${ROOT}/設定/章立て.json`).chapters).toEqual([{ name: "第二章", startEpisodePath: "本文/第5話_灯台の朝.txt", note: "残す" }]);
    const posting = json(store, `${ROOT}/設定/投稿状態.json`);
    expect(posting.posts.map((p: { episodePath: string }) => p.episodePath)).toEqual(["本文/第5話_灯台の朝.txt", "本文/第4話 港.txt"]);
    expect(posting.posts[0].bodyHash).toBe("v3:abc");
    expect(posting.revisions[0].episodePath).toBe("本文/第5話_灯台の朝.txt");
    expect(posting.futureField).toEqual({ keep: true });
    expect(json(store, `${ROOT}/設定/timeline.json`).episodes[0]).toEqual({ filePath: "本文/第5話_灯台の朝.txt", at: "春" });
    expect(json(store, `${ROOT}/設定/書籍/book.json`).illustrations[0]).toEqual({ episodePath: "本文/第5話_灯台の朝.txt", line: 3 });
    expect(json(store, `${ROOT}/設定/chapter_synopses.json`).episodes[0]).toMatchObject({ chapter: 5, fileName: "第5話_灯台の朝.txt", title: "灯台の朝", synopsis: "霧の朝" });
    const movedReading = `${ROOT}/.aiwriter/readings/${readingDictionaryFileName("本文/第5話_灯台の朝.txt")}`;
    expect(text(store, reading)).toBeUndefined();
    expect(json(store, movedReading)).toEqual({ episode: "本文/第5話_灯台の朝.txt", entries: [{ word: "霧笛", reading: "むてき" }] });
  });

  test("台帳が無い作品でも名前は変わる", async () => {
    const store = work();
    expect((await renameEpisodeWithLedgers({ store, root: ROOT, path: EP, subtitle: "灯台の朝" })).ok).toBe(true);
    expect(text(store, NEW)).toBe(BODY);
  });

  test("壊れた台帳・知らない新しい形の台帳が1つでもあれば、名前を変えない（どのファイルも変わらない）", async () => {
    for (const [file, content] of [
      [`${ROOT}/設定/投稿状態.json`, "{ 壊れ"],
      [`${ROOT}/設定/章立て.json`, JSON.stringify({ schemaVersion: "9", chapters: [{ name: "第二章", startEpisodePath: "本文/第5話.txt" }] })],
    ] as const) {
      const store = work({ [file]: content });
      const outcome = await renameEpisodeWithLedgers({ store, root: ROOT, path: EP, subtitle: "灯台の朝" });
      expect(outcome.ok).toBe(false);
      expect(text(store, EP)).toBe(BODY);
      expect(text(store, NEW)).toBeUndefined();
      expect(text(store, file)).toBe(content);
    }
  });

  test("新しい名前が既にある・競合の話・書きかけの控えがある話・校閲中の話は、名前を変えない", async () => {
    const taken = work({ [NEW]: "別の話" });
    expect(await renameEpisodeWithLedgers({ store: taken, root: ROOT, path: EP, subtitle: "灯台の朝" })).toEqual({ ok: false, message: "第5話_灯台の朝.txt が既にあります" });
    expect(text(taken, NEW)).toBe("別の話");

    const conflicted = work();
    expect((await renameEpisodeWithLedgers({ store: conflicted, root: ROOT, path: EP, subtitle: "灯台の朝", undecidedConflicts: [EP] })).ok).toBe(false);

    const drafted = work({ [journalPathFor(EP)]: "#novelai-draft\n書きかけ" });
    const outcome = await renameEpisodeWithLedgers({ store: drafted, root: ROOT, path: EP, subtitle: "灯台の朝" });
    expect(outcome.ok).toBe(false);
    if (!outcome.ok) expect(outcome.message).toContain("書きかけの控え");

    const locked = work({ [`${ROOT}/.aiwriter/locks/locks.jsonl`]: `${JSON.stringify({ kind: "acquire", file: "本文/第5話.txt", holder: "編集部", holderKind: "editor", time: new Date().toISOString(), note: "校閲中" })}\n` });
    const lockedOutcome = await renameEpisodeWithLedgers({ store: locked, root: ROOT, path: EP, subtitle: "灯台の朝" });
    expect(lockedOutcome.ok).toBe(false);
    for (const store of [conflicted, drafted, locked]) expect(text(store, EP)).toBe(BODY);
  });

  test("話数の読めない話のあらすじは、ファイル名で引くので付け替える", async () => {
    const path = `${ROOT}/本文/あとがき.txt`;
    const store = work({
      [path]: "あとがき",
      [`${ROOT}/設定/chapter_synopses.json`]: JSON.stringify({ schemaVersion: "0.1", episodes: [{ chapter: null, fileName: "あとがき.txt", title: null, synopsis: "後書き", autoGenerated: true }] }),
    });
    expect((await renameEpisodeWithLedgers({ store, root: ROOT, path, subtitle: "ありがとう" })).ok).toBe(true);
    expect(json(store, `${ROOT}/設定/chapter_synopses.json`).episodes[0].fileName).toBe("あとがき_ありがとう.txt");
  });
});

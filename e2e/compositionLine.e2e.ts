import { expect, test } from "@playwright/test";
import { FAKE_WORKS, openWithWorks, readFakeFile } from "./support/fakeWorks";

/**
 * **変換中の線：左（既定）／右（テスト中）**（設定 → 表示。`src/app/episodeScreen.ts`。引継ぎ書 76章）。
 * 右は字と変換中の線をこの画面が描く欄（EditContext）。作品は作り物（`_確認用`）だけ
 */

const EPISODE = "灯台守_確認用/本文/第1話 手紙.txt";

/** 本体の `emptyCharacter` と同じ形の人物（e2e からは本体の部品を読めないので、形を写す） */
const character = (id: string, name: string, extra: Record<string, unknown> = {}) => JSON.stringify({ ...{"schemaVersion":"0.1","aliases":[],"distinctFrom":[],"reading":null,"romaji":null,"icon":null,"iconSource":"none","summary":null,"gender":null,"affiliation":null,"role":null,"personality":null,"personalityFacets":[],"speechStyle":null,"speechStyleFacets":[],"appearance":null,"physical":null,"firstPerson":{"default":null,"variants":[]},"defaultSecondPerson":null,"addressTerms":[],"relations":[],"rejectedRelations":[],"abilities":[],"appearedChapters":[],"status":"登場済み","spoilerLevel":"public","authorNotes":"","exportNote":"","autoGenerated":true,"isMob":false,"evidence":null,"conflicts":[],"changes":[],"aiNotes":[],"customFields":{},"updatedAt":""}, id, name, ...extra });

test.describe("変換中の線", () => {
  test("既定は左（ブラウザの入力欄）。設定で右にすると、テスト中の断りが出て、原稿エディターがこの画面の描く欄になる。打った字も道具帯も保存される", async ({ page }) => {
    await openWithWorks(page, "#/display");
    await expect(page.locator('[data-line="left"]')).toHaveAttribute("aria-pressed", "true");
    await expect(page.locator(".line-choice + .flag")).toHaveCount(0);
    await page.locator('[data-line="right"]').click();
    await expect(page.locator('[data-line="right"]')).toHaveAttribute("aria-pressed", "true");
    await expect(page.locator("#lineSlot .flag.warn")).toContainText("テスト中");

    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator("#episodeSlot .ep").first().click();
    const editor = page.locator("#msEditor");
    await expect(editor).toHaveAttribute("data-line", "right");
    await expect(editor).toContainText("姉から手紙が届いた。");
    // 道具帯：カーソルの所（終わり）に「」を入れ、カーソルは括弧の中
    await editor.click();
    await page.keyboard.press("End");
    await page.locator('[data-tool="brackets"]').click();
    await page.keyboard.type("abc");
    await expect(page.locator("#saveState")).toHaveText("保存済み", { timeout: 6000 });
    expect(await readFakeFile(page, EPISODE)).toContain("「abc」");

    // 左に戻すと、ふつうの入力欄
    await page.evaluate(() => (location.hash = "#/display"));
    await page.locator('[data-line="left"]').click();
    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator("#episodeSlot .ep").first().click();
    await expect(page.locator("textarea#msEditor")).toBeVisible();
  });

  test("右の線の欄では、作品の設定資料の人物に色が付く（モブは付かない）。設定へは書かない", async ({ page }) => {
    const sister = character("char_001", "姉");
    const mob = character("char_002", "手紙", { isMob: true });
    await openWithWorks(page, "#/display", {
      ...FAKE_WORKS,
      "灯台守_確認用/設定/characters/char_001.json": sister,
      "灯台守_確認用/設定/characters/char_002.json": mob,
    });
    await page.locator('[data-line="right"]').click();
    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator("#episodeSlot .ep").first().click();
    const editor = page.locator("#msEditor");
    await expect(editor).toContainText("姉から手紙が届いた。");
    await expect(editor.locator(".term-character").first()).toHaveText("姉");
    await expect(editor.locator(".term-character")).toHaveCount(1);
    expect(await readFakeFile(page, "灯台守_確認用/設定/characters/char_001.json")).toBe(sister);
  });

  test("シリーズでつないだ隣の作品の、公開・登場済みの人物にも色が付く（未登場は付かない）。相手へは書かない", async ({ page }) => {
    const letter = character("char_001", "手紙");
    const sister = character("char_002", "姉", { status: "未登場" });
    await openWithWorks(page, "#/display", {
      ...FAKE_WORKS,
      "灯台守_確認用/.aiwriter/config.json": JSON.stringify({ workTitle: "灯台守の手紙_確認用", series: { name: "灯台守", related: ["灯台守外伝_確認用"] } }),
      "灯台守外伝_確認用/.aiwriter/config.json": JSON.stringify({ workTitle: "灯台守外伝_確認用" }),
      "灯台守外伝_確認用/設定/characters/char_001.json": letter,
      "灯台守外伝_確認用/設定/characters/char_002.json": sister,
    });
    await page.locator('[data-line="right"]').click();
    await page.evaluate(() => (location.hash = "#/works"));
    await page.locator(".work-card", { hasText: "灯台守の手紙_確認用" }).click();
    await page.locator("#episodeSlot .ep").first().click();
    const editor = page.locator("#msEditor");
    await expect(editor).toContainText("姉から手紙が届いた。");
    // 右の線の欄は1字ずつ描くので、色の付いた字をつないで見る（「姉」は未登場なので付かない）
    await expect(editor.locator(".term-character")).toHaveText(["手", "紙"]);
    expect(await readFakeFile(page, "灯台守外伝_確認用/設定/characters/char_001.json")).toBe(letter);
  });
});

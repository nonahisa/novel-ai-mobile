import { describe, expect, it } from "vitest";
import { emptyCharacter, parseCharacter } from "novel-ai-assistant/src/models/character";
import { emptyLocation, parseLocation } from "novel-ai-assistant/src/models/location";
import { emptyAbility } from "novel-ai-assistant/src/models/ability";
import { emptyOrganization } from "novel-ai-assistant/src/models/organization";
import { emptyWorldItem, parseWorldItem } from "novel-ai-assistant/src/models/world";
import { MemoryFileStore } from "../src/platform/memoryFileStore";
import { readRecordFile } from "../src/platform/materialEnrich";
import { changedValues, editFieldsOf, saveMaterialEdits } from "../src/platform/materialEdit";
import { renderEditForm } from "../src/app/materialEditScreen";

/**
 * 設定資料の1件を手で直す（2026-11-27 作者の答え「全部の欄」）。本体の設定資料パネルと同じ欄・同じ反映の部品
 * （`apply*Edits`。作者が直したので `autoGenerated: false`）。作品は作り物（`_確認用`）だけ
 */
const enc = (text: string) => new TextEncoder().encode(text);
const dec = (bytes: Uint8Array) => new TextDecoder().decode(bytes);
const ROOT = "灯台守_確認用";
const SET = `${ROOT}/設定`;
const SISTER = `${SET}/characters/char_001.json`;
const NOW = "2026-11-27T00:00:00.000Z";

function storeWith(extra: Record<string, string> = {}): MemoryFileStore {
  const store = new MemoryFileStore();
  const files: Record<string, string> = {
    [`${ROOT}/.aiwriter/config.json`]: JSON.stringify({ workTitle: "灯台守の手紙_確認用" }),
    [SISTER]: `${JSON.stringify(
      { ...emptyCharacter("char_001", "姉"), summary: "灯台に住む姉", authorNotes: "妹には甘い", exportNote: "公開しない", customFields: { birthday: "三月三日" } },
      null,
      2
    )}\n`,
    [`${SET}/characters/char_002.json`]: `${JSON.stringify(emptyCharacter("char_002", "灯"), null, 2)}\n`,
    [`${SET}/locations/loc_001.json`]: `${JSON.stringify(emptyLocation("loc_001", "灯台"), null, 2)}\n`,
    [`${SET}/locations/loc_002.json`]: `${JSON.stringify(emptyLocation("loc_002", "港町"), null, 2)}\n`,
    [`${SET}/abilities/abil_001.json`]: `${JSON.stringify(emptyAbility("abil_001", "霧読み"), null, 2)}\n`,
    [`${SET}/organizations/org_001.json`]: `${JSON.stringify(emptyOrganization("org_001", "灯台局"), null, 2)}\n`,
    [`${SET}/world/world_001_霧笛の決まり.json`]: `${JSON.stringify(emptyWorldItem("world_001", "霧笛の決まり", "rule"), null, 2)}\n`,
    [`${SET}/custom_fields.json`]: JSON.stringify({ schemaVersion: "0.1", fields: [{ key: "birthday", label: "誕生日", hint: "", multiline: false }] }),
    ...extra,
  };
  for (const [path, text] of Object.entries(files)) store.putExternally(path, enc(text));
  return store;
}

async function open(store: MemoryFileStore, kind: "character" | "location" | "ability" | "organization" | "world", id: string) {
  const file = await readRecordFile(store, SET, kind, id);
  if (!file) throw new Error("見つからない");
  return file;
}

const keys = (fields: { key: string }[]) => fields.map((field) => field.key);

describe("直せる欄（本体の設定資料パネルと同じ並び）", () => {
  it("人物：名前から資料用の補足まで、作者が足した項目も含めて全部", async () => {
    const store = storeWith();
    const fields = await editFieldsOf(store, SET, await open(store, "character", "char_001"));
    expect(keys(fields)).toEqual([
      "name",
      "summary",
      "gender",
      "affiliation",
      "reading",
      "aliases",
      "aliasReadings",
      "role",
      "personality",
      "speechStyle",
      "appearance",
      "relations",
      "isMob",
      "isProtagonist",
      "dwellings",
      "custom:birthday",
      "authorNotes",
      "exportNote",
    ]);
    const byKey = Object.fromEntries(fields.map((field) => [field.key, field]));
    expect(byKey["summary"]!.value).toBe("灯台に住む姉");
    expect(byKey["custom:birthday"]).toMatchObject({ label: "誕生日", value: "三月三日" });
    expect(byKey["authorNotes"]).toMatchObject({ label: "作者メモ", value: "妹には甘い", multiline: true });
    expect(byKey["isMob"]).toMatchObject({ check: true, value: "" });
  });

  it("能力・組織・場所・世界観も、それぞれの欄（世界観の分類は決まった値から選ぶ）", async () => {
    const store = storeWith();
    expect(keys(await editFieldsOf(store, SET, await open(store, "ability", "abil_001")))).toEqual([
      "name", "summary", "reading", "aliases", "aliasReadings", "category", "description", "cost", "limitation", "authorNotes", "exportNote",
    ]);
    expect(keys(await editFieldsOf(store, SET, await open(store, "organization", "org_001")))).toEqual([
      "name", "summary", "reading", "aliases", "aliasReadings", "category", "parent", "description", "authorNotes", "exportNote",
    ]);
    expect(keys(await editFieldsOf(store, SET, await open(store, "location", "loc_001")))).toEqual([
      "name", "summary", "reading", "aliases", "aliasReadings", "region", "relations", "description", "authorNotes", "exportNote",
    ]);
    const world = await editFieldsOf(store, SET, await open(store, "world", "world_001"));
    expect(keys(world)).toEqual(["name", "category", "reading", "aliases", "aliasReadings", "description", "authorNotes", "exportNote"]);
    const category = world.find((field) => field.key === "category")!;
    expect(category.value).toBe("rule");
    expect(category.choices?.map((choice) => choice.value)).toContain("society");
  });
});

describe("保存（変えた欄だけを本体の部品で当てる）", () => {
  it("変えた欄だけが変わり、作者メモ・資料用の補足・作者が足した項目は、触らなければそのまま。作者が直したので autoGenerated は false", async () => {
    const store = storeWith();
    const file = await open(store, "character", "char_001");
    const fields = await editFieldsOf(store, SET, file);
    const now = Object.fromEntries(fields.map((field) => [field.key, field.value]));
    now["personality"] = "静かで、よく笑う";
    const changed = changedValues(fields, now);
    expect(changed).toEqual({ personality: "静かで、よく笑う" });
    const result = await saveMaterialEdits(store, SET, file, changed, NOW);
    expect(result).toMatchObject({ ok: true });
    const saved = parseCharacter(JSON.parse(dec(await store.readFile(SISTER))));
    expect(saved.personality).toBe("静かで、よく笑う");
    expect(saved.summary).toBe("灯台に住む姉");
    expect(saved.authorNotes).toBe("妹には甘い");
    expect(saved.exportNote).toBe("公開しない");
    expect(saved.customFields).toEqual({ birthday: "三月三日" });
    expect(saved.autoGenerated).toBe(false);
    expect(saved.updatedAt).toBe(NOW);
  });

  it("作者メモ・作者が足した項目・モブの印・関係も、作者が直せば変わる", async () => {
    const store = storeWith();
    const file = await open(store, "character", "char_001");
    const result = await saveMaterialEdits(
      store,
      SET,
      file,
      { authorNotes: "妹には厳しい", "custom:birthday": "四月一日", isMob: "1", relations: "灯=弟" },
      NOW
    );
    expect(result).toMatchObject({ ok: true });
    const saved = parseCharacter(JSON.parse(dec(await store.readFile(SISTER))));
    expect(saved.authorNotes).toBe("妹には厳しい");
    expect(saved.customFields).toEqual({ birthday: "四月一日" });
    expect(saved.isMob).toBe(true);
    expect(saved.relations.map((relation) => [relation.name, relation.relation])).toEqual([["灯", "弟"]]);
  });

  it("何も変えていなければ書かない", async () => {
    const store = storeWith();
    const file = await open(store, "character", "char_001");
    const before = dec(await store.readFile(SISTER));
    expect(await saveMaterialEdits(store, SET, file, {}, NOW)).toMatchObject({ ok: false });
    expect(dec(await store.readFile(SISTER))).toBe(before);
  });

  it("名前を空にする・読めない関係の行は、訳を出して書かない（黙って捨てない）", async () => {
    const store = storeWith();
    const file = await open(store, "character", "char_001");
    const before = dec(await store.readFile(SISTER));
    const empty = await saveMaterialEdits(store, SET, file, { name: "" }, NOW);
    expect(empty).toMatchObject({ ok: false });
    expect(empty.notice).toContain("名前は空にできません");
    const bad = await saveMaterialEdits(store, SET, file, { relations: "だれでもない行" }, NOW);
    expect(bad).toMatchObject({ ok: false });
    expect(dec(await store.readFile(SISTER))).toBe(before);
  });

  it("読んだあとで外で変わったファイルには書かない（同期で入れ替わった資料を上書きしない）", async () => {
    const store = storeWith();
    const file = await open(store, "character", "char_001");
    store.putExternally(SISTER, enc(`${JSON.stringify({ ...emptyCharacter("char_001", "姉"), summary: "パソコンで直した" }, null, 2)}\n`));
    const result = await saveMaterialEdits(store, SET, file, { personality: "x" }, NOW);
    expect(result).toMatchObject({ ok: false });
    expect(parseCharacter(JSON.parse(dec(await store.readFile(SISTER)))).summary).toBe("パソコンで直した");
  });

  it("名前を変えても、ファイルは同じ場所に書く（消さない・作り直さない）", async () => {
    const store = storeWith();
    const file = await open(store, "world", "world_001");
    expect(await saveMaterialEdits(store, SET, file, { name: "霧笛の掟" }, NOW)).toMatchObject({ ok: true });
    const path = `${SET}/world/world_001_霧笛の決まり.json`;
    expect(parseWorldItem(JSON.parse(dec(await store.readFile(path)))).name).toBe("霧笛の掟");
    expect((await store.listFiles(`${SET}/world`)).sort()).toEqual(["world_001_霧笛の決まり.json"]);
  });

  it("場所の位置関係は、台帳の場所へ引き当てる（本体と同じ）", async () => {
    const store = storeWith();
    const file = await open(store, "location", "loc_001");
    expect(await saveMaterialEdits(store, SET, file, { relations: "港町の北" }, NOW)).toMatchObject({ ok: true });
    const saved = parseLocation(JSON.parse(dec(await store.readFile(`${SET}/locations/loc_001.json`))));
    expect(saved.relations?.[0]).toMatchObject({ target: "港町", targetId: "loc_002" });
  });
});

describe("画面の組み立て", () => {
  it("欄ごとに入力を出し、チェックと選ぶ欄はその形。値は字のまま（HTML にしない）", async () => {
    const store = storeWith({
      [`${SET}/characters/char_003.json`]: `${JSON.stringify({ ...emptyCharacter("char_003", "<b>船乗り</b>"), isMob: true }, null, 2)}\n`,
    });
    const html = renderEditForm(await editFieldsOf(store, SET, await open(store, "character", "char_003")));
    expect(html).toContain('value="&lt;b&gt;船乗り&lt;/b&gt;"');
    expect(html).not.toContain("<b>船乗り");
    expect(html).toMatch(/data-key="isMob"[^]*?type="checkbox"[^>]* checked/);
    expect(html).toMatch(/data-key="authorNotes"[^]*?<textarea/);
  });
});
